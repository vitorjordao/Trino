/// Targets whose every input costs a GPU frame: the stable mutation run
/// (`crates/fuzz/tests/targets.rs`, `fuzz smoke`) gives them fewer
/// iterations.
pub const SLOW_TARGETS: &[&str] = &["pc_renderer"];

/// How many of `iters` mutations the stable runs give target `name`.
pub fn iters_for(name: &str, iters: usize) -> usize {
    if SLOW_TARGETS.contains(&name) {
        iters.min(48)
    } else {
        iters
    }
}

/// A target by name.
pub fn find(name: &str) -> Option<&'static Target> {
    TARGETS.iter().find(|t| t.name == name)
}

/// The repository root (this crate is `crates/fuzz`).
pub fn repo_root() -> PathBuf {
    // Not canonicalized: on Windows that gives a `\\?\` path, where a
    // later `join("fuzz/seeds")`'s `/` is no separator.
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../..")
}

/// The files directly in `dir`, sorted by name (empty when it is missing).
pub fn files_in(dir: &Path) -> Vec<PathBuf> {
    let mut v: Vec<PathBuf> = std::fs::read_dir(dir)
        .map(|r| {
            r.filter_map(|e| e.ok())
                .map(|e| e.path())
                .filter(|p| p.is_file())
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

/// The committed seeds of a target (`fuzz/seeds/<name>/`).
pub fn seeds(name: &str) -> Vec<Vec<u8>> {
    files_in(&repo_root().join("fuzz/seeds").join(name))
        .iter()
        .filter_map(|p| std::fs::read(p).ok())
        .collect()
}

/// The crash reproducers of a target (`fuzz/regressions/<name>/`).
pub fn regressions(name: &str) -> Vec<(PathBuf, Vec<u8>)> {
    files_in(&repo_root().join("fuzz/regressions").join(name))
        .into_iter()
        .filter_map(|p| std::fs::read(&p).ok().map(|b| (p, b)))
        .collect()
}

/// Run `target` on `data`; `Err` with the panic message when it panicked.
pub fn run_caught(target: &Target, data: &[u8]) -> Result<(), String> {
    let run = target.run;
    std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| run(data))).map_err(|e| {
        e.downcast_ref::<String>()
            .cloned()
            .or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string()))
            .unwrap_or_else(|| "panic".into())
    })
}

/// Run the target `name` on `data` (what each cargo-fuzz binary calls):
/// panics propagate, so libFuzzer records the input.
pub fn run(name: &str, data: &[u8]) {
    let t = find(name).unwrap_or_else(|| panic!("no fuzz target `{name}`"));
    if data.len() <= t.max_len {
        (t.run)(data);
    }
}
