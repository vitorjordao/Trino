//! Scene → `no_std` Rust data (`trino_core::scene::SceneNode`), so console
//! games can ship editor-made scenes with zero runtime parsing:
//!
//! ```text
//! cargo xtask scene export scenes/level1.scene.ron examples/mygame/src/level1_gen.rs
//! ```
//!
//! The output is deterministic (stable diffs) and marked as generated.

use std::fmt::Write;

use trino_core::{Color, Shading};

use crate::{Library, Scene, Target, resolve_for};

fn f(v: f32) -> String {
    // `{:?}` always prints a decimal point or exponent: a valid f32 literal.
    let v = if v == 0.0 { 0.0 } else { v }; // no "-0.0" churn
    format!("{v:?}")
}

fn color(c: Color) -> String {
    format!("Color::rgba({}, {}, {}, {})", c.r, c.g, c.b, c.a)
}

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Generate the Rust module text for `scene` as the PC sees it. Returns
/// (code, warnings).
pub fn to_rust(scene: &Scene, lib: &Library) -> (String, Vec<String>) {
    to_rust_for(scene, lib, Target::Pc)
}

/// [`to_rust`] with `target`'s platform variants applied (`cargo xtask scene
/// export --platform n64`).
pub fn to_rust_for(scene: &Scene, lib: &Library, target: Target) -> (String, Vec<String>) {
    let resolved = resolve_for(scene, lib, 0.0, target);
    let mut out = String::new();
    let platform = match target {
        Target::Pc => String::new(),
        t => format!(" --platform {}", t.key()),
    };
    let _ = writeln!(
        out,
        "// @generated by trino-scene from scene `{}` — do not edit.\n\
         // Regenerate: cargo xtask scene export{platform} <scene.ron> <this file>\n",
        esc(&scene.name)
    );
    let _ = writeln!(
        out,
        "#[allow(unused_imports)]\nuse trino_core::{{\n    AmbientOcclusion, AoQuality, Camera3, ClipId, Collider, Color, DetailTexture, Fog, Impostor,\n    Light, LodLevel, Lods, Mat34, ModelId, ModelParams, NO_CELL, SceneNode, Shading, Shape,\n    SoundId, SoundSource, SpriteId, Tags, TexFilter, Vec2, Vec3, VisVolume, Water,\n}};\n"
    );
    let env = &scene.environment;
    let cam = env.core_camera();
    let light = env.core_light();
    let _ = writeln!(
        out,
        "pub const CLEAR: Color = Color::rgb({}, {}, {});",
        env.clear[0], env.clear[1], env.clear[2]
    );
    let _ = writeln!(
        out,
        "pub const CAMERA: Camera3 = Camera3 {{\n    eye: Vec3::new({}, {}, {}),\n    target: Vec3::new({}, {}, {}),\n    fov_y: {},\n}};",
        f(cam.eye.x),
        f(cam.eye.y),
        f(cam.eye.z),
        f(cam.target.x),
        f(cam.target.y),
        f(cam.target.z),
        f(cam.fov_y)
    );
    let _ = writeln!(
        out,
        "pub const LIGHT: Light = Light {{\n    dir: Vec3::new({}, {}, {}),\n    ambient: {},\n    color: {},\n    ambient_color: {},\n    fog: Fog {{ color: {}, near: {}, far: {} }},\n}};\n",
        f(light.dir.x),
        f(light.dir.y),
        f(light.dir.z),
        f(light.ambient),
        color(light.color),
        color(light.ambient_color),
        color(light.fog.color),
        f(light.fog.near),
        f(light.fog.far)
    );
    // Screen-space AO (PC native; consoles ignore it — their AO is baked
    // into the models).
    let ao = match env.core_ao() {
        Some(a) => format!(
            "Some(AmbientOcclusion {{\n    radius: {},\n    intensity: {},\n    bias: {},\n    quality: AoQuality::{:?},\n}})",
            f(a.radius),
            f(a.intensity),
            f(a.bias),
            a.quality
        ),
        None => "None".into(),
    };
    let _ = writeln!(out, "pub const AO: Option<AmbientOcclusion> = {ao};\n");

    // Asset groups (issue #56): only for a scene that has them, so a
    // boot-only scene's module is what it always was.
    let cells: Vec<(usize, &String)> = resolved
        .cell_groups
        .iter()
        .enumerate()
        .flat_map(|(c, gs)| gs.iter().map(move |g| (c, g)))
        .collect();
    if scene.requires != ["boot"] || !cells.is_empty() {
        let id = |g: &str| format!("trino_core::GroupId::from_name(\"{}\")", esc(g));
        let requires: Vec<String> = scene.requires.iter().map(|g| id(g)).collect();
        let _ = writeln!(
            out,
            "/// The asset groups the scene needs loaded (`requires`).\npub const REQUIRES: &[trino_core::GroupId] = &[{}];",
            requires.join(", ")
        );
        let _ = writeln!(
            out,
            "/// (cell, group): what each cell streams (`trino_core::CellGroups::add`).\npub const CELL_GROUPS: &[(u8, trino_core::GroupId)] = &["
        );
        for (c, g) in cells {
            let _ = writeln!(out, "    ({c}, {}),", id(g));
        }
        let _ = writeln!(out, "];\n");
    }

    let _ = writeln!(out, "pub static NODES: &[SceneNode] = &[");
    for item in resolved.items.iter().filter(|i| i.exported()) {
        let m = &item.matrix.m;
        let rows: Vec<String> = m
            .iter()
            .map(|r| format!("[{}, {}, {}, {}]", f(r[0]), f(r[1]), f(r[2]), f(r[3])))
            .collect();
        let model = match &item.model {
            Some((id, path)) => format!("Some(ModelId({:#010x})) /* {} */", id.0, esc(path)),
            None => "None".into(),
        };
        let p = &item.params;
        let shading = match p.shading {
            Shading::Gouraud => "Gouraud",
            Shading::Flat => "Flat",
            Shading::Unlit => "Unlit",
        };
        let anim = match p.anim {
            Some(a) => {
                // resolve() ran at t = 0 with time = 0 * speed; recover the
                // speed from the component.
                let speed = scene_speed(scene, &item.owner).unwrap_or(1.0);
                format!("Some((ClipId({:#010x}), {}))", a.clip.0, f(speed))
            }
            None => "None".into(),
        };
        let v3 = |v: trino_core::Vec3| format!("Vec3::new({}, {}, {})", f(v.x), f(v.y), f(v.z));
        let collider = match item.collider {
            Some(c) => {
                let shape = match c.shape {
                    trino_core::Shape::Box { half } => {
                        format!("Shape::Box {{ half: {} }}", v3(half))
                    }
                    trino_core::Shape::Sphere { radius } => {
                        format!("Shape::Sphere {{ radius: {} }}", f(radius))
                    }
                    trino_core::Shape::Capsule { radius, height } => format!(
                        "Shape::Capsule {{ radius: {}, height: {} }}",
                        f(radius),
                        f(height)
                    ),
                };
                format!(
                    "Some(Collider {{\n            shape: {shape},\n            offset: {},\n            trigger: {},\n        }})",
                    v3(c.offset),
                    c.trigger
                )
            }
            None => "None".into(),
        };
        let lod = if item.lod.is_empty() {
            "Lods::NONE".to_string()
        } else {
            let levels: Vec<String> = item
                .lod
                .iter()
                .map(|l| {
                    let (model, impostor) = match &l.draw {
                        crate::LodDraw::Model(id, path) => (
                            format!("Some(ModelId({:#010x})) /* {} */", id.0, esc(path)),
                            "None".to_string(),
                        ),
                        crate::LodDraw::Impostor(path, i) => (
                            "None".to_string(),
                            format!(
                                "Some(Impostor {{ sprite: SpriteId({:#010x}), views: {}, cols: {}, \
                                 tile: {}, size: {}, center: {} }}) /* {} */",
                                i.sprite.0,
                                i.views,
                                i.cols,
                                i.tile,
                                f(i.size),
                                v3(i.center),
                                esc(path)
                            ),
                        ),
                        crate::LodDraw::Cull => ("None".to_string(), "None".to_string()),
                    };
                    format!(
                        "LodLevel {{ distance: {}, model: {model}, impostor: {impostor} }}",
                        f(l.distance)
                    )
                })
                .collect();
            format!("Lods::List(&[{}])", levels.join(", "))
        };
        let tags: Vec<String> = item
            .tags
            .iter()
            .map(|t| format!("\"{}\"", esc(t)))
            .collect();
        let _ = writeln!(
            out,
            "    SceneNode {{\n        name: \"{}\",\n        tags: Tags::List(&[{}]),\n        matrix: Mat34 {{\n            m: [{}],\n        }},\n        model: {},\n        params: ModelParams {{\n            tint: {},\n            emissive: {},\n            shading: Shading::{},\n            double_sided: {},\n            anim: None,\n            texture: {},\n            palette: None,\n            gloss: {},\n            filter: TexFilter::{:?},\n            detail: {},\n            water: {},\n        }},\n        anim: {},\n        collider: {},\n        lod: {},\n        sound: {},\n        cell: {},\n        vis: {},\n    }},",
            esc(&item.name),
            tags.join(", "),
            rows.join(", "),
            model,
            color(p.tint),
            color(p.emissive),
            shading,
            p.double_sided,
            match p.texture {
                Some(t) => format!("Some(SpriteId({:#010x}))", t.0),
                None => "None".into(),
            },
            p.gloss,
            p.filter,
            match p.detail {
                Some(d) => format!(
                    "Some(DetailTexture {{ sprite: SpriteId({:#010x}), scale_log2: {} }})",
                    d.sprite.0, d.scale_log2
                ),
                None => "None".into(),
            },
            match p.water {
                Some(w) => format!(
                    "Some(Water {{ flow_speed: Vec2::new({}, {}), detail_flow: Vec2::new({}, {}), wave_amplitude: {}, wave_frequency: {}, ripple_responsiveness: {} }})",
                    f(w.flow_speed.x),
                    f(w.flow_speed.y),
                    f(w.detail_flow.x),
                    f(w.detail_flow.y),
                    f(w.wave_amplitude),
                    f(w.wave_frequency),
                    f(w.ripple_responsiveness)
                ),
                None => "None".into(),
            },
            anim,
            collider,
            lod,
            match item.sound {
                Some(snd) => format!(
                    "Some(SoundSource {{ sound: SoundId({:#010x}), radius: {}, volume: {} }})",
                    snd.sound.0,
                    f(snd.radius),
                    f(snd.volume)
                ),
                None => "None".into(),
            },
            if item.cell == trino_core::NO_CELL {
                "NO_CELL".to_string()
            } else {
                item.cell.to_string()
            },
            match item.vis {
                Some(trino_core::VisVolume::Cell { half }) => {
                    format!("Some(VisVolume::Cell {{ half: {} }})", v3(half))
                }
                Some(trino_core::VisVolume::Portal { half, a, b }) => format!(
                    "Some(VisVolume::Portal {{ half: {}, a: {a}, b: {b} }})",
                    v3(half)
                ),
                None => "None".into(),
            }
        );
    }
    let _ = writeln!(out, "];");
    (out, resolved.warnings)
}

fn scene_speed(scene: &Scene, owner: &[usize]) -> Option<f32> {
    scene
        .get(owner)?
        .model
        .as_ref()?
        .anim
        .as_ref()
        .map(|a| a.speed)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{AnimComponent, Entity, ModelComponent};

    #[test]
    fn generates_deterministic_node_data() {
        let mut scene = Scene::new("demo");
        let mut e = Entity::new("robot")
            .at([1.0, 0.0, -2.0])
            .with_model(ModelComponent {
                anim: Some(AnimComponent {
                    clip: "walk".into(),
                    speed: 1.5,
                }),
                ..ModelComponent::new("models/robot")
            });
        e.tags.push("enemy".into());
        scene.entities.push(e);
        scene.entities.push(Entity::new("spawn"));
        let lib = Library::default();
        let (a, warnings) = to_rust(&scene, &lib);
        let (b, _) = to_rust(&scene, &lib);
        assert_eq!(a, b);
        assert!(warnings.is_empty());
        assert!(a.contains("name: \"robot\""));
        assert!(a.contains("tags: Tags::List(&[\"enemy\"])"));
        assert!(a.contains(&format!(
            "ModelId({:#010x})",
            trino_core::asset_id("models/robot")
        )));
        assert!(a.contains(&format!(
            "ClipId({:#010x}), 1.5",
            trino_core::asset_id("walk")
        )));
        assert!(a.contains("name: \"spawn\""));
        assert!(a.contains("pub const CAMERA"));
    }
}
