r=0x1234_5678
def nxt():
    global r
    r^=(r<<13)&0xffffffff; r^=r>>17; r^=(r<<5)&0xffffffff
    return (r>>8)/(1<<24)
def f(x): return f"{x:.2f}"
ents=[]
def box(name,x,y,z,w,h,d,extra=""):
    shape=f"Box(size: ({f(w)}, {f(h)}, {f(d)}))"
    if extra=="ramp":
        shape=f"Ramp(size: ({f(w)}, {f(h)}, {f(d)}), dir: {['PosX','NegX','PosZ','NegZ'][int(nxt()*4)%4]})"
    ow=", one_way: true" if extra=="oneway" else ""
    return f"""(
    name: "{name}",
    transform: (
        pos: ({f(x)}, {f(y)}, {f(z)}),
        rot: (0.0, 0.0, 0.0),
        scale: (1.0, 1.0, 1.0),
    ),
    collider: Some((shape: {shape}, offset: (0.0, {f(h/2)}, 0.0){ow})),
),"""
out=[]
