//! Generated masters for the showcase's river (issue #49, ADR 0015), all
//! built from `showcase::river` (the course the game walks on, so meshes
//! and collision agree):
//!
//! - `models/showcase/terrain.glb`: the ground carved by the channel (the
//!   corridor's cross-sections, a sloped spring basin and the ground around
//!   it, ear-clipped), vertex-colored grass, mud and a darker bed;
//! - `models/showcase/river.glb`: the water ribbon, 17 rings × 5 points
//!   (16 × 4 quads, 128 triangles), UVs across (u) and downstream (v),
//!   deep and opaque in the middle, turquoise and translucent at the banks;
//! - `models/showcase/bridge.glb`: an arched plank bridge with rails;
//! - `sprites/textures/tex_water.png` and `tex_ripples.png`: the two 32×32
//!   tiling layers (I8 and I4 on the N64: 1 KB + 512 B of TMEM);
//! - `sprites/fx_drop.png`: the splash droplet;
//! - `sounds/water_splash.wav` and `sounds/river_flow.wav` (a loop).
//!
//! Regenerated by `cargo xtask gen-assets`.

use std::f32::consts::TAU;
use std::path::Path;

use showcase::river::{
    BANK_RUN, BED_IN, BED_Y, BRIDGE_DECK, BRIDGE_HALF_W, BRIDGE_RISE, BRIDGE_X, BRIDGE_Z0,
    BRIDGE_Z1, COURSE, RIBBON_OVER, SPRING_RUN, WATER_Y,
};
use trino_core::{Vec2, Vec3};

use crate::castle64_assets::PngWriter;

type Rgba = [u8; 4];

/// The water texture repeats every this many meters downstream.
const UV_TILE: f32 = 3.0;

#[derive(Default)]
struct Mesh {
    positions: Vec<Vec3>,
    normals: Vec<Vec3>,
    colors: Vec<Rgba>,
    uvs: Vec<Vec2>,
    indices: Vec<u16>,
}

impl Mesh {
    fn vert(&mut self, p: Vec3, n: Vec3, c: Rgba) -> u16 {
        self.positions.push(p);
        self.normals.push(n);
        self.colors.push(c);
        (self.positions.len() - 1) as u16
    }

    /// Triangle `a b c`, wound so its face normal points along `up`.
    fn tri(&mut self, a: u16, b: u16, c: u16, up: Vec3) {
        let (pa, pb, pc) = (
            self.positions[a as usize],
            self.positions[b as usize],
            self.positions[c as usize],
        );
        if (pb - pa).cross(pc - pa).dot(up) >= 0.0 {
            self.indices.extend_from_slice(&[a, b, c]);
        } else {
            self.indices.extend_from_slice(&[a, c, b]);
        }
    }

    /// A flat-shaded quad (its own 4 vertices), wound to face `out`.
    fn quad(&mut self, pts: [Vec3; 4], out: Vec3, c: Rgba) {
        let n = (pts[1] - pts[0]).cross(pts[2] - pts[0]).normalized();
        let n = if n.dot(out) < 0.0 { -n } else { n };
        let i: Vec<u16> = pts.iter().map(|&p| self.vert(p, n, c)).collect();
        self.tri(i[0], i[1], i[2], n);
        self.tri(i[0], i[2], i[3], n);
    }

    fn tris(&self) -> usize {
        self.indices.len() / 3
    }

    /// Hand-assembled GLB (JSON + BIN): POSITION, NORMAL, COLOR_0 (linear,
    /// see `color0_linear`), TEXCOORD_0 when the mesh has UVs.
    fn write_glb(&self, path: &Path) {
        let mut bin: Vec<u8> = Vec::new();
        let mut views: Vec<(usize, usize)> = Vec::new();
        let mut push = |bin: &mut Vec<u8>, bytes: &[u8]| {
            let at = bin.len();
            bin.extend_from_slice(bytes);
            while !bin.len().is_multiple_of(4) {
                bin.push(0);
            }
            views.push((at, bytes.len()));
        };
        let f32s = |v: &mut Vec<u8>, xs: &[f32]| {
            for x in xs {
                v.extend_from_slice(&x.to_le_bytes());
            }
        };
        let mut pos = Vec::new();
        let mut nrm = Vec::new();
        let (mut min, mut max) = ([f32::MAX; 3], [f32::MIN; 3]);
        for (p, n) in self.positions.iter().zip(&self.normals) {
            f32s(&mut pos, &[p.x, p.y, p.z]);
            f32s(&mut nrm, &[n.x, n.y, n.z]);
            for (k, v) in [p.x, p.y, p.z].into_iter().enumerate() {
                min[k] = min[k].min(v);
                max[k] = max[k].max(v);
            }
        }
        let colors: Vec<u8> = self.colors.iter().flatten().copied().collect();
        let colors = crate::color0_linear(&colors);
        let mut idx = Vec::new();
        for i in &self.indices {
            idx.extend_from_slice(&i.to_le_bytes());
        }
        push(&mut bin, &pos);
        push(&mut bin, &nrm);
        push(&mut bin, &colors);
        push(&mut bin, &idx);
        let has_uv = !self.uvs.is_empty();
        if has_uv {
            assert_eq!(self.uvs.len(), self.positions.len());
            let mut uv = Vec::new();
            for t in &self.uvs {
                f32s(&mut uv, &[t.x, t.y]);
            }
            push(&mut bin, &uv);
        }
        let n = self.positions.len();
        let views_json: Vec<String> = views
            .iter()
            .map(|(at, len)| format!(r#"{{"buffer":0,"byteOffset":{at},"byteLength":{len}}}"#))
            .collect();
        let mut accessors = vec![
            format!(
                r#"{{"bufferView":0,"componentType":5126,"count":{n},"type":"VEC3","min":[{},{},{}],"max":[{},{},{}]}}"#,
                min[0], min[1], min[2], max[0], max[1], max[2]
            ),
            format!(r#"{{"bufferView":1,"componentType":5126,"count":{n},"type":"VEC3"}}"#),
            format!(r#"{{"bufferView":2,"componentType":5126,"count":{n},"type":"VEC4"}}"#),
            format!(
                r#"{{"bufferView":3,"componentType":5123,"count":{},"type":"SCALAR"}}"#,
                self.indices.len()
            ),
        ];
        let mut attrs = r#""POSITION":0,"NORMAL":1,"COLOR_0":2"#.to_string();
        if has_uv {
            accessors.push(format!(
                r#"{{"bufferView":4,"componentType":5126,"count":{n},"type":"VEC2"}}"#
            ));
            attrs.push_str(r#","TEXCOORD_0":4"#);
        }
        let json = format!(
            r#"{{"asset":{{"version":"2.0","generator":"trino gen-assets"}},"scene":0,"scenes":[{{"nodes":[0]}}],"nodes":[{{"mesh":0,"name":"m"}}],"meshes":[{{"primitives":[{{"attributes":{{{attrs}}},"indices":3}}]}}],"buffers":[{{"byteLength":{}}}],"bufferViews":[{}],"accessors":[{}]}}"#,
            bin.len(),
            views_json.join(","),
            accessors.join(","),
        );
        let mut json = json.into_bytes();
        while !json.len().is_multiple_of(4) {
            json.push(b' ');
        }
        let total = 12 + 8 + json.len() + 8 + bin.len();
        let mut glb = Vec::with_capacity(total);
        glb.extend_from_slice(b"glTF");
        glb.extend_from_slice(&2u32.to_le_bytes());
        glb.extend_from_slice(&(total as u32).to_le_bytes());
        glb.extend_from_slice(&(json.len() as u32).to_le_bytes());
        glb.extend_from_slice(b"JSON");
        glb.extend_from_slice(&json);
        glb.extend_from_slice(&(bin.len() as u32).to_le_bytes());
        glb.extend_from_slice(b"BIN\0");
        glb.extend_from_slice(&bin);
        std::fs::write(path, glb).unwrap();
    }
}

const UP: Vec3 = Vec3::new(0.0, 1.0, 0.0);

/// Unit flow direction at ring `i` (x z): the neighbors' chord.
fn tangent(i: usize) -> Vec2 {
    let a = COURSE[i.saturating_sub(1)];
    let b = COURSE[(i + 1).min(COURSE.len() - 1)];
    let d = Vec2::new(b.x - a.x, b.z - a.z);
    d * (1.0 / d.length_squared().sqrt())
}

/// Ring `i`'s point at lateral offset `d` (positive = left of the flow,
/// which is north for an eastward river) and height `y`.
fn ring_point(i: usize, d: f32, y: f32) -> Vec3 {
    let c = COURSE[i];
    let t = tangent(i);
    Vec3::new(c.x - t.y * d, y, c.z + t.x * d)
}

/// The water ribbon: 5 points across each ring (both edges under the bank,
/// the quarter lines and the middle).
fn river() -> Mesh {
    let mut m = Mesh::default();
    let mut along = 0.0f32;
    for i in 0..COURSE.len() {
        if i > 0 {
            let (a, b) = (COURSE[i - 1], COURSE[i]);
            along += ((b.x - a.x).powi(2) + (b.z - a.z).powi(2)).sqrt();
        }
        let w = COURSE[i].half_width + RIBBON_OVER;
        for k in 0..5 {
            let s = k as f32 / 2.0 - 1.0; // -1 .. 1
            let p = ring_point(i, s * w, WATER_Y);
            // Deep, opaque blue in the channel; turquoise, foamy and
            // translucent where it meets the banks.
            let c = match k {
                2 => [40, 104, 150, 232],
                1 | 3 => [58, 138, 170, 196],
                _ => [172, 228, 218, 92],
            };
            m.vert(p, UP, c);
            m.uvs.push(Vec2::new((s + 1.0) * 0.5, along / UV_TILE));
        }
    }
    for i in 0..COURSE.len() as u16 - 1 {
        for k in 0..4u16 {
            let (a, b) = (i * 5 + k, i * 5 + k + 1);
            let (c, d) = (a + 5, b + 5);
            m.tri(a, b, d, UP);
            m.tri(a, d, c, UP);
        }
    }
    m
}

const GRASS: Rgba = [118, 176, 84, 255];
const GRASS_DARK: Rgba = [96, 152, 70, 255];
const MUD: Rgba = [112, 98, 70, 255];
const BED: Rgba = [78, 82, 64, 255];

/// Ear clipping of a simple polygon (x z), any winding: triangle index
/// triples into `poly`.
fn ear_clip(poly: &[Vec2]) -> Vec<[usize; 3]> {
    let area: f32 = (0..poly.len())
        .map(|i| {
            let (a, b) = (poly[i], poly[(i + 1) % poly.len()]);
            a.x * b.y - b.x * a.y
        })
        .sum();
    let ccw = area > 0.0;
    let cross = |a: Vec2, b: Vec2, c: Vec2| (b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x);
    let convex = |a, b, c| {
        let k = cross(a, b, c);
        if ccw { k > 1e-9 } else { k < -1e-9 }
    };
    let inside = |p: Vec2, a: Vec2, b: Vec2, c: Vec2| {
        let (d1, d2, d3) = (cross(a, b, p), cross(b, c, p), cross(c, a, p));
        let neg = d1 < 0.0 || d2 < 0.0 || d3 < 0.0;
        let pos = d1 > 0.0 || d2 > 0.0 || d3 > 0.0;
        !(neg && pos)
    };
    let mut idx: Vec<usize> = (0..poly.len()).collect();
    let mut out = Vec::new();
    while idx.len() > 3 {
        let n = idx.len();
        let mut clipped = false;
        // Prefer the ear with the best shape (the largest smallest angle,
        // approximated by area over the longest edge squared): fewer
        // slivers for the fog and the depth splits to chew on.
        let mut best: Option<(f32, usize)> = None;
        for k in 0..n {
            let (i0, i1, i2) = (idx[(k + n - 1) % n], idx[k], idx[(k + 1) % n]);
            let (a, b, c) = (poly[i0], poly[i1], poly[i2]);
            if !convex(a, b, c) {
                continue;
            }
            if idx
                .iter()
                .any(|&j| j != i0 && j != i1 && j != i2 && inside(poly[j], a, b, c))
            {
                continue;
            }
            let l = (b - a)
                .length_squared()
                .max((c - b).length_squared())
                .max((a - c).length_squared());
            let q = cross(a, b, c).abs() / l;
            if best.is_none_or(|(bq, _)| q > bq) {
                best = Some((q, k));
            }
        }
        if let Some((_, k)) = best {
            out.push([idx[(k + n - 1) % n], idx[k], idx[(k + 1) % n]]);
            idx.remove(k);
            clipped = true;
        }
        assert!(clipped, "ear clipping: no ear in a polygon of {n}");
    }
    out.push([idx[0], idx[1], idx[2]]);
    out
}

/// The ground carved by the channel.
fn terrain() -> Mesh {
    let mut m = Mesh::default();
    let rings = COURSE.len();
    // Corridor: 4 points per ring (both bank tops, both bed edges).
    let mut ring = Vec::new();
    for (i, c) in COURSE.iter().enumerate() {
        let hw = c.half_width;
        let (top, bed) = (hw - BED_IN + BANK_RUN, hw - BED_IN);
        let pts = [
            (ring_point(i, top, 0.0), GRASS),
            (ring_point(i, bed, BED_Y), BED),
            (ring_point(i, -bed, BED_Y), BED),
            (ring_point(i, -top, 0.0), GRASS),
        ];
        // Smooth normals across each slope (they're lit, not flat).
        let r: Vec<u16> = pts.iter().map(|&(p, c)| m.vert(p, UP, c)).collect();
        ring.push(r);
    }
    for i in 0..rings - 1 {
        for k in 0..3 {
            let (a, b) = (ring[i][k], ring[i][k + 1]);
            let (c, d) = (ring[i + 1][k], ring[i + 1][k + 1]);
            m.tri(a, b, d, UP);
            m.tri(a, d, c, UP);
        }
    }
    // The spring: the bed rises to the ground at an apex upstream.
    let t0 = tangent(0);
    let c0 = COURSE[0];
    let apex_p = Vec3::new(c0.x - t0.x * SPRING_RUN, 0.0, c0.z - t0.y * SPRING_RUN);
    let apex = m.vert(apex_p, UP, MUD);
    for k in 0..3 {
        m.tri(ring[0][k], ring[0][k + 1], apex, UP);
    }
    // The ground around: the square minus the channel's slot, entering from
    // the east edge (north bank west, round the spring, south bank east).
    let mut outline: Vec<u16> = Vec::new();
    outline.extend(ring.iter().rev().map(|r| r[0]));
    outline.push(apex);
    outline.extend(ring.iter().map(|r| r[3]));
    for (x, z, c) in [
        (20.0, -20.0, GRASS_DARK),
        (-20.0, -20.0, GRASS),
        (-20.0, 20.0, GRASS_DARK),
        (20.0, 20.0, GRASS),
    ] {
        outline.push(m.vert(Vec3::new(x, 0.0, z), UP, c));
    }
    // Bank-top points keep their grass color but get their own copies for
    // the flat ground (an up normal; the corridor's are smoothed below).
    let poly: Vec<Vec2> = outline
        .iter()
        .map(|&v| {
            let p = m.positions[v as usize];
            Vec2::new(p.x, p.z)
        })
        .collect();
    let ground: Vec<u16> = outline
        .iter()
        .map(|&v| {
            let (p, c) = (m.positions[v as usize], m.colors[v as usize]);
            m.vert(p, UP, if c == MUD { GRASS } else { c })
        })
        .collect();
    for [a, b, c] in ear_clip(&poly) {
        m.tri(ground[a], ground[b], ground[c], UP);
    }
    smooth_normals(&mut m, ring.iter().flatten().copied().chain([apex]));
    m
}

/// Area-weighted vertex normals for the listed vertices (the corridor),
/// from the triangles that use them.
fn smooth_normals(m: &mut Mesh, verts: impl Iterator<Item = u16>) {
    let mut acc = vec![Vec3::ZERO; m.positions.len()];
    for t in m.indices.chunks(3) {
        let (a, b, c) = (
            m.positions[t[0] as usize],
            m.positions[t[1] as usize],
            m.positions[t[2] as usize],
        );
        let n = (b - a).cross(c - a);
        for &i in t {
            acc[i as usize] += n;
        }
    }
    for v in verts {
        m.normals[v as usize] = acc[v as usize].normalized();
    }
}

const WOOD: Rgba = [150, 102, 62, 255];
const WOOD_DARK: Rgba = [112, 74, 44, 255];
const WOOD_LIGHT: Rgba = [176, 126, 80, 255];

/// The arched plank bridge over the river at `BRIDGE_X` (world placement:
/// the model is authored in world coordinates, the scene puts it at the
/// origin).
fn bridge() -> Mesh {
    let mut m = Mesh::default();
    const SEGS: usize = 6;
    let (x0, x1) = (BRIDGE_X - BRIDGE_HALF_W, BRIDGE_X + BRIDGE_HALF_W);
    let deck = |t: f32| {
        let z = BRIDGE_Z0 + (BRIDGE_Z1 - BRIDGE_Z0) * t;
        let s = t * 2.0 - 1.0;
        (z, BRIDGE_RISE * (1.0 - s * s))
    };
    for s in 0..SEGS {
        let (za, ya) = deck(s as f32 / SEGS as f32);
        let (zb, yb) = deck((s + 1) as f32 / SEGS as f32);
        let plank = if s % 2 == 0 { WOOD } else { WOOD_LIGHT };
        let (ba, bb) = (ya - BRIDGE_DECK, yb - BRIDGE_DECK);
        // Top, the two sides, the underside.
        m.quad(
            [
                Vec3::new(x0, ya, za),
                Vec3::new(x1, ya, za),
                Vec3::new(x1, yb, zb),
                Vec3::new(x0, yb, zb),
            ],
            UP,
            plank,
        );
        for (x, out) in [(x0, -1.0), (x1, 1.0)] {
            m.quad(
                [
                    Vec3::new(x, ba, za),
                    Vec3::new(x, ya, za),
                    Vec3::new(x, yb, zb),
                    Vec3::new(x, bb, zb),
                ],
                Vec3::new(out, 0.0, 0.0),
                WOOD_DARK,
            );
        }
        m.quad(
            [
                Vec3::new(x0, ba, za),
                Vec3::new(x0, bb, zb),
                Vec3::new(x1, bb, zb),
                Vec3::new(x1, ba, za),
            ],
            -UP,
            WOOD_DARK,
        );
    }
    // Rails: posts at the ends and the middle, a beam along the arch.
    const RAIL: f32 = 0.5;
    const POST: f32 = 0.08;
    for x in [x0 + POST, x1 - POST] {
        for t in [0.0f32, 0.5, 1.0] {
            let (z, y) = deck(t.clamp(0.04, 0.96));
            let (lo, hi) = (y - 0.05, y + RAIL);
            // The outer and inner faces only: the ends are 16 cm wide.
            for (dx, out) in [
                (-POST, Vec3::new(-1.0, 0.0, 0.0)),
                (POST, Vec3::new(1.0, 0.0, 0.0)),
            ] {
                let (ax, az, bx, bz) = (x + dx, z - POST, x + dx, z + POST);
                m.quad(
                    [
                        Vec3::new(ax, lo, az),
                        Vec3::new(bx, lo, bz),
                        Vec3::new(bx, hi, bz),
                        Vec3::new(ax, hi, az),
                    ],
                    out,
                    WOOD_DARK,
                );
            }
        }
        for s in 0..3 {
            let (za, ya) = deck(s as f32 / 3.0);
            let (zb, yb) = deck((s + 1) as f32 / 3.0);
            let (ya, yb) = (ya + RAIL, yb + RAIL);
            let h = 0.07;
            m.quad(
                [
                    Vec3::new(x - POST, ya, za),
                    Vec3::new(x + POST, ya, za),
                    Vec3::new(x + POST, yb, zb),
                    Vec3::new(x - POST, yb, zb),
                ],
                UP,
                WOOD_LIGHT,
            );
            // Its outer side (the inner one faces the deck, barely seen).
            let (sx, out) = if x < BRIDGE_X {
                (-POST, -1.0)
            } else {
                (POST, 1.0)
            };
            {
                m.quad(
                    [
                        Vec3::new(x + sx, ya - h, za),
                        Vec3::new(x + sx, ya, za),
                        Vec3::new(x + sx, yb, zb),
                        Vec3::new(x + sx, yb - h, zb),
                    ],
                    Vec3::new(out, 0.0, 0.0),
                    WOOD,
                );
            }
        }
    }
    m
}

/// A tiling 32×32 grayscale layer, white alpha (`f` gives 0..1 per texel
/// at `(u, v)` in turns over the tile).
fn layer(f: impl Fn(f32, f32) -> f32) -> Vec<u8> {
    let mut px = Vec::with_capacity(32 * 32 * 4);
    for y in 0..32 {
        for x in 0..32 {
            let v = f(x as f32 / 32.0, y as f32 / 32.0).clamp(0.0, 1.0);
            let g = (v * 255.0).round() as u8;
            px.extend_from_slice(&[g, g, g, 255]);
        }
    }
    px
}

/// The base layer: soft streaks along the flow (v), bright 0.7..1.
fn water_texture() -> Vec<u8> {
    layer(|u, v| {
        let s = |k: f32, a: f32| (TAU * k * a).sin();
        let w = 0.5 * s(1.0, u + 0.15 * s(1.0, v))
            + 0.3 * s(2.0, v + 0.25 * s(1.0, u))
            + 0.2 * s(3.0, u + v);
        0.84 + 0.14 * w
    })
}

/// The detail layer: caustic-like bright lines (cells' edges), tiling.
fn ripple_texture() -> Vec<u8> {
    // Jittered cell centers on a 4×4 grid (deterministic).
    let mut seeds = Vec::new();
    let mut s = 0x9E37_79B9u32;
    let mut rnd = || {
        s ^= s << 13;
        s ^= s >> 17;
        s ^= s << 5;
        (s % 1000) as f32 / 1000.0
    };
    for gy in 0..4 {
        for gx in 0..4 {
            seeds.push(Vec2::new(
                (gx as f32 + 0.2 + 0.6 * rnd()) / 4.0,
                (gy as f32 + 0.2 + 0.6 * rnd()) / 4.0,
            ));
        }
    }
    layer(|u, v| {
        // Distances to the two nearest centers, wrapped (tiling).
        let (mut d1, mut d2) = (f32::MAX, f32::MAX);
        for c in &seeds {
            for oy in [-1.0, 0.0, 1.0] {
                for ox in [-1.0, 0.0, 1.0] {
                    let d = Vec2::new(u - c.x - ox, v - c.y - oy)
                        .length_squared()
                        .sqrt();
                    if d < d1 {
                        d2 = d1;
                        d1 = d;
                    } else if d < d2 {
                        d2 = d;
                    }
                }
            }
        }
        let edge = (d2 - d1) * 4.0 * 4.0;
        0.62 + 0.38 * (1.0 - edge.min(1.0)).powi(3)
    })
}

/// The splash droplet: an 8×8 soft white dot.
fn droplet() -> Vec<u8> {
    let mut px = Vec::with_capacity(8 * 8 * 4);
    for y in 0..8 {
        for x in 0..8 {
            let d = Vec2::new(x as f32 - 3.5, y as f32 - 3.5)
                .length_squared()
                .sqrt()
                / 4.0;
            let a = ((1.0 - d) * 1.6).clamp(0.0, 1.0);
            px.extend_from_slice(&[255, 255, 255, (a * 255.0).round() as u8]);
        }
    }
    px
}

fn wav(path: &Path, rate: u32, samples: &[f32], gain: f32) {
    let spec = hound::WavSpec {
        channels: 1,
        sample_rate: rate,
        bits_per_sample: 16,
        sample_format: hound::SampleFormat::Int,
    };
    let mut w = hound::WavWriter::create(path, spec).unwrap();
    for s in samples {
        w.write_sample((s.clamp(-1.0, 1.0) * gain * i16::MAX as f32) as i16)
            .unwrap();
    }
    w.finalize().unwrap();
}

struct Noise(u32);

impl Noise {
    fn next(&mut self) -> f32 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 17;
        self.0 ^= self.0 << 5;
        (self.0 as f32 / u32::MAX as f32) * 2.0 - 1.0
    }
}

/// A splash: a noise burst that darkens as it decays, plus a "bloop" that
/// falls in pitch.
fn splash() -> Vec<f32> {
    let rate = 22_050.0;
    let n = (rate * 0.45) as usize;
    let mut noise = Noise(0x5A1A_5A1A);
    let (mut lp, mut phase) = (0.0f32, 0.0f32);
    (0..n)
        .map(|i| {
            let t = i as f32 / rate;
            let env = (-t * 9.0).exp();
            // The low-pass closes as the splash settles.
            lp += (noise.next() - lp) * (0.55 - t).clamp(0.08, 0.55);
            let f = 520.0 * (-t * 5.0).exp() + 180.0;
            phase += f / rate;
            let bloop = (phase * TAU).sin() * (-t * 14.0).exp() * 0.6;
            (lp * 1.6 * env + bloop).clamp(-1.0, 1.0)
        })
        .collect()
}

/// A river's murmur: low-passed noise with slow swells and a few trickles,
/// crossfaded into a seamless 3 s loop.
fn river_flow() -> Vec<f32> {
    let rate = 22_050usize;
    let n = rate * 3;
    let fade = rate / 3;
    let mut noise = Noise(0x0F10_0F10);
    let (mut lp1, mut lp2, mut hp) = (0.0f32, 0.0f32, 0.0f32);
    let raw: Vec<f32> = (0..n + fade)
        .map(|i| {
            let t = i as f32 / rate as f32;
            let x = noise.next();
            lp1 += (x - lp1) * 0.12;
            lp2 += (lp1 - lp2) * 0.2;
            // A brighter trickle layer, swelling on its own clock.
            hp += (x - hp) * 0.45;
            let swell = 0.75 + 0.25 * (t * TAU / 1.5).sin();
            let trickle = (hp - lp1) * 0.35 * (0.5 + 0.5 * (t * TAU / 0.75 + 1.0).sin());
            lp2 * 2.4 * swell + trickle
        })
        .collect();
    let mut out = raw[..n].to_vec();
    for i in 0..fade {
        let k = i as f32 / fade as f32;
        out[i] = out[i] * k + raw[n + i] * (1.0 - k);
    }
    out
}

/// The water self-test's sheet (`castle64::selftest::water`): 4 × 4 m at
/// y 0, 8 × 8 quads (vertices every 0.5 m, enough for the swell), UVs one
/// repeat per 2 m, one translucent blue.
fn selftest_water() -> Mesh {
    let mut m = Mesh::default();
    const N: u16 = 8;
    for j in 0..=N {
        for i in 0..=N {
            let (x, z) = (i as f32 * 0.5 - 2.0, j as f32 * 0.5 - 2.0);
            m.vert(Vec3::new(x, 0.0, z), UP, [90, 170, 255, 160]);
            m.uvs.push(Vec2::new(x * 0.5, z * 0.5));
        }
    }
    for j in 0..N {
        for i in 0..N {
            let a = j * (N + 1) + i;
            let (b, c, d) = (a + 1, a + N + 1, a + N + 2);
            m.tri(a, b, d, UP);
            m.tri(a, d, c, UP);
        }
    }
    m
}

/// Write every river master under `root/assets/shared/`.
pub fn gen_all(root: &Path, write_png: PngWriter) {
    let shared = root.join("assets/shared");
    let models = shared.join("models/showcase");
    let textures = shared.join("sprites/textures");
    std::fs::create_dir_all(&models).unwrap();
    std::fs::create_dir_all(&textures).unwrap();
    std::fs::create_dir_all(shared.join("models/proxies")).unwrap();
    let r = river();
    assert_eq!(r.tris(), 128, "the ribbon is 16 x 4 quads");
    r.write_glb(&models.join("river.glb"));
    terrain().write_glb(&models.join("terrain.glb"));
    bridge().write_glb(&models.join("bridge.glb"));
    selftest_water().write_glb(&shared.join("models/proxies/selftest-water.glb"));
    write_png(&textures.join("tex_water.png"), 32, 32, &water_texture());
    write_png(&textures.join("tex_ripples.png"), 32, 32, &ripple_texture());
    write_png(&shared.join("sprites/fx_drop.png"), 8, 8, &droplet());
    let sounds = shared.join("sounds");
    wav(&sounds.join("water_splash.wav"), 22_050, &splash(), 0.7);
    wav(&sounds.join("river_flow.wav"), 22_050, &river_flow(), 0.5);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn terrain_matches_the_course_the_game_walks_on() {
        let t = terrain();
        // Every vertex sits where `showcase::river::terrain_height` says the
        // ground is (the corridor's, the spring's and the square's).
        for p in &t.positions {
            if p.x.abs() >= 19.9 || p.z.abs() >= 19.9 {
                continue; // the square's corners (and the east edge)
            }
            let h = showcase::river::terrain_height(p.x, p.z);
            assert!((h - p.y).abs() < 0.06, "{p:?}: mesh {} vs walk {h}", p.y);
        }
        // Every triangle faces up (the ground is seen from above).
        for c in t.indices.chunks(3) {
            let (a, b, d) = (
                t.positions[c[0] as usize],
                t.positions[c[1] as usize],
                t.positions[c[2] as usize],
            );
            assert!((b - a).cross(d - a).y >= -1e-6, "{a:?} {b:?} {d:?}");
        }
        assert!(t.tris() < 160, "{} triangles", t.tris());
        assert!(
            bridge().tris() <= 96,
            "{} bridge triangles",
            bridge().tris()
        );
    }

    #[test]
    fn the_ribbon_is_under_the_banks_and_flows_downstream() {
        let r = river();
        assert_eq!(r.positions.len(), 17 * 5);
        for (p, uv) in r.positions.iter().zip(&r.uvs) {
            assert_eq!(p.y, WATER_Y);
            assert!((0.0..=1.0).contains(&uv.x));
        }
        // v grows downstream; alpha drops toward the banks.
        assert!(r.uvs[5 * 16].y > r.uvs[0].y + 10.0);
        assert!(r.colors[0][3] < r.colors[2][3]);
    }

    #[test]
    fn ear_clipping_covers_the_polygon() {
        let sq = [
            Vec2::new(0.0, 0.0),
            Vec2::new(2.0, 0.0),
            Vec2::new(2.0, 2.0),
            Vec2::new(1.0, 1.0),
            Vec2::new(0.0, 2.0),
        ];
        let tris = ear_clip(&sq);
        assert_eq!(tris.len(), 3);
        let area: f32 = tris
            .iter()
            .map(|t| {
                let (a, b, c) = (sq[t[0]], sq[t[1]], sq[t[2]]);
                ((b.x - a.x) * (c.y - a.y) - (b.y - a.y) * (c.x - a.x)).abs() * 0.5
            })
            .sum();
        assert!((area - 3.0).abs() < 1e-5, "{area}");
    }
}
