impl S {
    /// The last string id: tests walk the enum up to it, so a string added
    /// after it must move it.
    pub const LAST: S = S::StadiumPark;

    /// A hair style's name, by [`crate::render::HairStyle`] index.
    pub fn hair_style(i: usize) -> S {
        [
            S::HairCrop,
            S::HairBuzz,
            S::HairCurly,
            S::HairLong,
            S::HairMohawk,
            S::HairBald,
        ][i % 6]
    }
}

