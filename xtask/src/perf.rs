//! Console performance gates for `cargo xtask test n64`: the self-test ROM
//! prints one `TRINO_PERF_SCENE:` line per `castle64::perf` scene
//! (`trino_core::perf::RenderProfile::write_report`). Two checks:
//!
//! - **Work** (`tests/perf/castle64_work.toml`, owned by
//!   `xtask/tests/perf_budget.rs`): the ROM's T&L counters must equal the
//!   PC's exactly — the software T&L is deterministic across targets, so a
//!   difference is a backend or build bug, not noise.
//! - **Time** (`tests/perf/castle64_n64.toml`): emulated N64 microseconds
//!   must stay under per-scene ceilings. ares is deterministic for a
//!   given ROM, but **code layout** is not neutral: adding an unrelated
//!   1 KB function moved the hub's T&L by -10% and its RDP submit by +20%
//!   (16 KB direct-mapped I-cache), while the whole frame moved 5%. So the
//!   frame total has a tight-ish ceiling and the stages loose ones — a
//!   net against real slowdowns, not a stopwatch; the exact work counters
//!   above catch content and algorithm regressions deterministically.
//!   `--bless` rewrites the ceilings from the measurement plus
//!   [`headroom`]; an optimization should bless them down so the gain is
//!   kept.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

pub const WORK_FILE: &str = "tests/perf/castle64_work.toml";
pub const N64_FILE: &str = "tests/perf/castle64_n64.toml";

/// T&L counters compared with the PC baseline.
const WORK_FIELDS: [&str; 7] = [
    "verts",
    "tris_in",
    "clipped",
    "splits",
    "backfaced",
    "emitted",
    "culled",
];

/// Ceiling = measured × (1 + headroom) + [`SLACK_US`]: the frame total
/// moves ~5% with code layout, single stages up to ~20%.
fn headroom(field: &str) -> f64 {
    if field == "frame_us" { 0.20 } else { 0.35 }
}
const SLACK_US: u64 = 500;

/// One `TRINO_PERF_SCENE:<name> key=value ...` line.
#[derive(Debug, Clone, PartialEq)]
pub struct SceneLine {
    pub name: String,
    pub fields: BTreeMap<String, u64>,
}

impl SceneLine {
    pub fn parse(line: &str) -> Option<SceneLine> {
        let rest = &line[line.find("TRINO_PERF_SCENE:")? + "TRINO_PERF_SCENE:".len()..];
        let mut parts = rest.split_whitespace();
        let name = parts.next()?.to_string();
        let fields = parts
            .filter_map(|kv| {
                let (k, v) = kv.split_once('=')?;
                Some((k.to_string(), v.parse().ok()?))
            })
            .collect();
        Some(SceneLine { name, fields })
    }

    fn get(&self, k: &str) -> u64 {
        self.fields.get(k).copied().unwrap_or(0)
    }

    /// The gated timings, in emulated µs per frame. `frame` is the CPU's
    /// work — update + render minus `begin`, which mostly waits for a free
    /// framebuffer (vsync/RDP) and swings by milliseconds between runs.
    pub fn timings(&self) -> [(&'static str, u64); 4] {
        [
            (
                "frame_us",
                (self.get("update") + self.get("render")).saturating_sub(self.get("begin")),
            ),
            ("tnl_us", self.get("tnl")),
            ("sort_us", self.get("sort")),
            ("submit_us", self.get("submit")),
        ]
    }
}

fn ceiling(field: &str, measured: u64) -> u64 {
    let c = (measured as f64 * (1.0 + headroom(field))) as u64 + SLACK_US;
    c.div_ceil(100) * 100
}

/// Render `tests/perf/castle64_n64.toml` from a run.
pub fn render_ceilings(scenes: &[SceneLine]) -> String {
    let mut out = String::from(
        "# castle64 frame-cost ceilings on the N64, in emulated microseconds per\n\
         # frame (ares; `cargo xtask test n64` fails a scene above its ceiling).\n\
         # frame_us = update + render - begin (begin waits for vsync/RDP).\n\
         # Generated by `cargo xtask test n64 --bless`: measured + 0.5 ms + 20%\n\
         # (frame) or 35% (stages) — code layout alone moves a stage ~20%.\n\
         # Bless after an optimization too, so the gain is kept. 60 fps = 16667,\n\
         # 30 fps = 33333.\n",
    );
    for s in scenes {
        let _ = writeln!(out, "\n[{}]", s.name);
        for (k, v) in s.timings() {
            let _ = writeln!(out, "{k} = {}", ceiling(k, v));
        }
    }
    out
}

/// Compare a run with the baselines. `Ok` carries a summary table.
pub fn check(work: &str, n64: Option<&str>, scenes: &[SceneLine]) -> Result<String, String> {
    let work: toml::Table = toml::from_str(work).map_err(|e| format!("{WORK_FILE}: {e}"))?;
    let n64: Option<toml::Table> = n64
        .map(|t| toml::from_str(t).map_err(|e| format!("{N64_FILE}: {e}")))
        .transpose()?;
    if scenes.is_empty() {
        return Err("no TRINO_PERF_SCENE lines in the ROM's output".into());
    }
    let mut errors = String::new();
    let mut table =
        String::from("scene         frame_us (ceiling)   tnl_us (model est)  sort_us  submit_us\n");
    let mut drift = String::new();
    for s in scenes {
        match work.get(&s.name).and_then(|v| v.as_table()) {
            None => {
                let _ = writeln!(errors, "  {}: not in {WORK_FILE}", s.name);
            }
            Some(want) => {
                for f in WORK_FIELDS {
                    let expected = want.get(f).and_then(|v| v.as_integer()).unwrap_or(-1);
                    let got = s.get(f) as i64;
                    if expected != got {
                        let _ = writeln!(
                            errors,
                            "  {}.{f}: ROM {got}, PC baseline {expected} (T&L not deterministic \
                             across targets, or the baseline is stale)",
                            s.name
                        );
                    }
                }
            }
        }
        let t = s.timings();
        // The calibrated cost model (trino_core::perf::N64_COST) on this
        // scene's work: tools trust it, so say when it drifts.
        let work_now = trino_core::TnlStats {
            culled: s.get("culled") as u32,
            verts: s.get("verts") as u32,
            tris_in: s.get("tris_in") as u32,
            clipped: s.get("clipped") as u32,
            splits: s.get("splits") as u32,
            backfaced: s.get("backfaced") as u32,
            emitted: s.get("emitted") as u32,
        };
        let est = trino_core::perf::N64_COST.tnl_us(&work_now, s.get("draws") as u32) as u64;
        if s.get("draws") > 0 && t[1].1 > 0 {
            let off = est as f64 / t[1].1 as f64 - 1.0;
            if off.abs() > 0.25 {
                let _ = writeln!(
                    drift,
                    "  note: {} T&L {} us vs cost-model {} us ({:+.0}%) — recalibrate \
                     N64_COST (n64-performance skill)",
                    s.name,
                    t[1].1,
                    est,
                    off * 100.0
                );
            }
        }
        let limits = n64
            .as_ref()
            .and_then(|n| n.get(&s.name))
            .and_then(|v| v.as_table());
        let limit = |k: &str| limits.and_then(|l| l.get(k)).and_then(|v| v.as_integer());
        let _ = writeln!(
            table,
            "{:<13} {:>8} ({:>8})  {:>7} ({:>7})  {:>7}  {:>9}",
            s.name,
            t[0].1,
            limit("frame_us").map_or("-".into(), |v| v.to_string()),
            t[1].1,
            est,
            t[2].1,
            t[3].1
        );
        if n64.is_some() {
            for (k, v) in t {
                match limit(k) {
                    Some(max) if v as i64 > max => {
                        let _ = writeln!(
                            errors,
                            "  {}.{k}: {v} us > ceiling {max} us (+{:.1}%)",
                            s.name,
                            (v as f64 / max as f64 - 1.0) * 100.0
                        );
                    }
                    Some(_) => {}
                    None => {
                        let _ = writeln!(errors, "  {}.{k}: no ceiling in {N64_FILE}", s.name);
                    }
                }
            }
        }
    }
    if n64.is_none() {
        let _ = writeln!(errors, "  {N64_FILE} missing — create it with --bless");
    }
    table.push_str(&drift);
    if errors.is_empty() {
        Ok(table)
    } else {
        Err(format!("{table}{errors}"))
    }
}

/// The `test n64` step: check (or, with `bless`, rewrite the ceilings).
pub fn gate(root: &Path, scenes: &[SceneLine], bless: bool) -> Result<String, String> {
    let work =
        std::fs::read_to_string(root.join(WORK_FILE)).map_err(|e| format!("{WORK_FILE}: {e}"))?;
    if bless {
        let text = render_ceilings(scenes);
        std::fs::write(root.join(N64_FILE), &text).map_err(|e| format!("{N64_FILE}: {e}"))?;
        // Work counters are still checked: blessing never hides a
        // determinism break.
        let table = check(&work, Some(&text), scenes)?;
        return Ok(format!("blessed {N64_FILE}\n{table}"));
    }
    let n64 = std::fs::read_to_string(root.join(N64_FILE)).ok();
    check(&work, n64.as_deref(), scenes)
}

#[cfg(test)]
mod tests {
    use super::*;

    const LINE: &str = "[ares] TRINO_PERF_SCENE:hub frames=4 update=250 render=190000 \
                        begin=4000 tnl=146000 sort=9800 submit=24000 sprites=700 end=30 \
                        game=4000 vblanks=47 verts=3260 tris_in=1770 clipped=40 splits=504 \
                        backfaced=1204 emitted=1074 culled=1";
    const WORK: &str = "[hub]\nverts = 3260\ntris_in = 1770\nclipped = 40\nsplits = 504\n\
                        backfaced = 1204\nemitted = 1074\nculled = 1\n";

    #[test]
    fn parses_a_scene_line() {
        let s = SceneLine::parse(LINE).unwrap();
        assert_eq!(s.name, "hub");
        assert_eq!(s.get("tnl"), 146000);
        assert_eq!(s.timings()[0], ("frame_us", 250 + 190000 - 4000));
        assert!(SceneLine::parse("[ares] TRINO_PERF:castle64 hub").is_none());
    }

    #[test]
    fn blessed_ceilings_pass_and_regressions_fail() {
        let s = SceneLine::parse(LINE).unwrap();
        let ceil = render_ceilings(std::slice::from_ref(&s));
        assert!(check(WORK, Some(&ceil), std::slice::from_ref(&s)).is_ok());
        // 1.5x slower T&L busts the 35% stage headroom.
        let mut slow = s.clone();
        slow.fields.insert("tnl".into(), 146000 * 15 / 10);
        let err = check(WORK, Some(&ceil), &[slow]).unwrap_err();
        assert!(err.contains("hub.tnl_us"), "{err}");
    }

    #[test]
    fn work_counters_must_match_the_pc_baseline() {
        let mut s = SceneLine::parse(LINE).unwrap();
        s.fields.insert("emitted".into(), 1075);
        let ceil = render_ceilings(std::slice::from_ref(&s));
        let err = check(WORK, Some(&ceil), &[s]).unwrap_err();
        assert!(
            err.contains("hub.emitted: ROM 1075, PC baseline 1074"),
            "{err}"
        );
    }

    #[test]
    fn ceilings_round_up_with_headroom() {
        assert_eq!(ceiling("frame_us", 0), 500);
        assert_eq!(ceiling("frame_us", 10_000), 12_500);
        assert_eq!(ceiling("tnl_us", 10_000), 14_000);
        assert_eq!(ceiling("tnl_us", 146_356), 198_100);
    }
}
