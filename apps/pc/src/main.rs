//! PC glue binary: winit window + trino-platform-pc backend + example game.
//!
//! Assets are baked on startup from `assets/` into `target/assets/pc` and
//! loaded by stable handle. With `--features reload`:
//! - editing a master asset rebakes and re-uploads it live (same handle);
//! - editing game code rebuilds the dylib (via `cargo xtask watch pc`) and
//!   hot-lib-reloader swaps the functions under the running state.
//!
//! Env knobs:
//! - `TRINO_SMOKE_FRAMES=N` — exit cleanly after N frames (CI smoke tests),
//!   printing a `TRINO_FRAME:` line (frame time, draws, the PC GPU T&L split)
//!   and a `TRINO_TEXTURES:` line (sprite textures on the GPU, BC ones).
//! - `TRINO_BC=0` — no BC textures: decoded RGBA8, as on a GPU without BC.
//! - `TRINO_SIM=native|n64|3ds|web` — console simulation profile (default
//!   n64); `n64x` / `3dsnew` add the expanded hardware tier (the N64 with
//!   the Expansion Pak, the New 3DS: the tier's `Caps` and `hw_tier`).
//! - `TRINO_SCENE=scenes/x.scene.ron` — play an editor scene instead of the
//!   game (reloads on scene/prefab/material edits; see `scene_player`).
//! - `TRINO_GAME=showcase` — run `examples/showcase` (the editor's demo
//!   scene exported to `no_std` code — the exact path console builds take)
//!   instead of castle64.
//! - `TRINO_GAME=solid-eleven` — run `examples/solid-eleven` (the football
//!   demo) on `trino-runner-pc`, the host its template uses: its own assets
//!   (`examples/solid-eleven/assets`, baked to `target/solid-eleven/assets/pc`),
//!   display settings, key and pad rebinding, MSAA on the native profile.

mod scene_player;

use std::path::PathBuf;
use std::sync::Arc;
use std::time::Instant;

#[cfg(not(feature = "reload"))]
use trino_core::Game;
use trino_core::{Input, Vec2};
use trino_platform_pc::{PcAudio, PcInput, PcPlatform, PcRenderer, SimProfile};

use winit::application::ApplicationHandler;
use winit::dpi::LogicalSize;
use winit::event::WindowEvent;
use winit::event_loop::{ActiveEventLoop, EventLoop};
use winit::window::{Window, WindowId};

#[cfg(feature = "reload")]
#[hot_lib_reloader::hot_module(
    dylib = "castle64",
    lib_dir = concat!(env!("CARGO_MANIFEST_DIR"), "/../../target/debug")
)]
mod hot_game {
    use castle64::Castle64Game;
    use trino_core::{Audio, InputState, Platform, Renderer};

    // Exports generated by trino_game_api::export_game! in the game crate
    // (macro expansion is invisible to hot_functions_from_file!, so the
    // signatures are declared explicitly).
    #[hot_functions]
    extern "Rust" {
        pub fn trino_game_api_version() -> u32;
        pub fn trino_game_update(
            state: &mut Castle64Game,
            platform: &mut dyn Platform,
            input: &InputState,
            audio: &mut dyn Audio,
            dt: f32,
        );
        pub fn trino_game_render(state: &mut Castle64Game, renderer: &mut dyn Renderer);
    }
}

/// `TRINO_GAME=solid-eleven`: the football demo, with its own asset set.
fn solid_eleven() -> bool {
    std::env::var("TRINO_GAME").as_deref() == Ok("solid-eleven")
}

fn assets_root() -> PathBuf {
    PathBuf::from("assets")
}

fn baked_dir() -> PathBuf {
    PathBuf::from("target/assets/pc")
}

struct Ctx {
    window: Arc<Window>,
    renderer: PcRenderer,
    audio: PcAudio,
    input: PcInput,
    platform: PcPlatform,
    game: castle64::Castle64Game,
    /// `TRINO_SCENE` mode: play an editor scene instead of the game.
    player: Option<scene_player::ScenePlayer>,
    /// `TRINO_GAME=showcase`: the codegen showcase instead of castle64.
    showcase: Option<showcase::ShowcaseGame>,
    last_frame: Instant,
    #[cfg(feature = "reload")]
    asset_events: std::sync::mpsc::Receiver<Vec<u32>>,
    #[cfg(feature = "reload")]
    _asset_watcher: Box<dyn std::any::Any>,
}

struct App {
    ctx: Option<Ctx>,
    profile: SimProfile,
    frames: u64,
    smoke_frames: Option<u64>,
    /// Frame time and the 3D split per frame, printed as a `TRINO_FRAME:`
    /// line when a smoke run ends.
    meter: trino_platform_pc::FrameMeter,
}

/// Upload (or re-upload) baked assets by handle (shared with standalone
/// projects through `trino-runner-pc`).
fn upload_assets(
    renderer: &mut PcRenderer,
    audio: &mut PcAudio,
    platform: &mut PcPlatform,
    only: Option<&[u32]>,
) -> Result<(), String> {
    trino_runner_pc::upload_assets(&baked_dir(), renderer, audio, platform, only)
}

impl App {
    fn init(&mut self, event_loop: &ActiveEventLoop) -> Ctx {
        let player = std::env::var("TRINO_SCENE").ok().map(|p| {
            scene_player::ScenePlayer::load(PathBuf::from(p)).unwrap_or_else(|e| panic!("{e}"))
        });
        let showcase = (std::env::var("TRINO_GAME").as_deref() == Ok("showcase")).then(|| {
            let (w, h) = self.profile.internal_resolution();
            showcase::ShowcaseGame::with_screen(Vec2::new(w as f32, h as f32))
        });
        let title = match (&player, &showcase) {
            (Some(p), _) => p.title(),
            (None, Some(_)) => "Trino — showcase (exported scene)".to_string(),
            _ => "Trino — castle64".to_string(),
        };
        let attrs = Window::default_attributes()
            .with_title(title)
            .with_inner_size(LogicalSize::new(1280.0, 720.0));
        let window = Arc::new(
            event_loop
                .create_window(attrs)
                .expect("failed to create window"),
        );

        let mut renderer =
            pollster::block_on(PcRenderer::new_windowed(window.clone(), self.profile))
                .expect("failed to initialize wgpu renderer");
        // `TRINO_SIM=n64x|3dsnew`: the console's expanded tier (#54).
        let tier = trino_runner_pc::tier_from_env();
        renderer.set_hw_tier(tier);
        let mut audio = PcAudio::new();
        // Saves go next to the build output, capped at the simulated
        // console's budget (an N64 profile gets the 2 KB EEPROM).
        let mut platform = PcPlatform::new(&self.profile.caps().with_tier(tier))
            .with_save_file(PathBuf::from("target/save/castle64.sav"));

        // Bake + load. Dev-time convenience: the app always starts fresh.
        trino_asset_pipeline::bake_all(
            &assets_root(),
            trino_asset_pipeline::Platform::Pc,
            &baked_dir(),
        )
        .unwrap_or_else(|e| panic!("{e}"));
        upload_assets(&mut renderer, &mut audio, &mut platform, None)
            .expect("failed to load baked assets");

        #[cfg(feature = "reload")]
        let (asset_events, watcher) = {
            let (tx, rx) = std::sync::mpsc::channel();
            let watcher = trino_asset_pipeline::watch::watch(
                assets_root(),
                trino_asset_pipeline::Platform::Pc,
                baked_dir(),
                move |changed| {
                    let _ = tx.send(changed);
                },
            )
            .expect("failed to start asset watcher");
            (rx, Box::new(watcher) as Box<dyn std::any::Any>)
        };

        let (iw, ih) = renderer.internal_size();
        let game = castle64::Castle64Game::new(Vec2::new(iw as f32, ih as f32));

        window.request_redraw();
        Ctx {
            window,
            renderer,
            audio,
            input: PcInput::new(),
            platform,
            game,
            player,
            showcase,
            last_frame: Instant::now(),
            #[cfg(feature = "reload")]
            asset_events,
            #[cfg(feature = "reload")]
            _asset_watcher: watcher,
        }
    }
}

impl ApplicationHandler for App {
    fn resumed(&mut self, event_loop: &ActiveEventLoop) {
        if self.ctx.is_none() {
            self.ctx = Some(self.init(event_loop));
        }
    }

    fn window_event(
        &mut self,
        event_loop: &ActiveEventLoop,
        _window_id: WindowId,
        event: WindowEvent,
    ) {
        let Some(ctx) = self.ctx.as_mut() else {
            return;
        };
        match event {
            WindowEvent::CloseRequested => event_loop.exit(),
            WindowEvent::Resized(size) => {
                ctx.renderer.resize(size.width, size.height);
            }
            ref e if ctx.input.handle_window_event(e, &ctx.renderer) => {}
            WindowEvent::RedrawRequested => {
                // Live asset reload: swap content under stable handles.
                #[cfg(feature = "reload")]
                while let Ok(changed) = ctx.asset_events.try_recv() {
                    match upload_assets(
                        &mut ctx.renderer,
                        &mut ctx.audio,
                        &mut ctx.platform,
                        Some(&changed),
                    ) {
                        Ok(()) => println!("assets reloaded: {} item(s)", changed.len()),
                        Err(e) => eprintln!("asset reload failed: {e}"),
                    }
                }

                let now = Instant::now();
                // Clamp dt: debugger pauses and window drags must not
                // teleport the simulation.
                let dt = (now - ctx.last_frame).as_secs_f32().min(0.1);
                ctx.last_frame = now;

                let input = ctx.input.poll();

                if let Some(player) = &mut ctx.player {
                    player.update(&input, dt);
                    player.render(&mut ctx.renderer);
                } else if let Some(game) = &mut ctx.showcase {
                    use trino_core::Game as _;
                    game.update_with(&mut ctx.platform, &input, &mut ctx.audio, dt);
                    game.render(&mut ctx.renderer);
                } else {
                    #[cfg(feature = "reload")]
                    {
                        let version = hot_game::trino_game_api_version();
                        assert_eq!(
                            version,
                            trino_game_api::GAME_API_VERSION,
                            "game dylib was built against a different game-api version — restart"
                        );
                        hot_game::trino_game_update(
                            &mut ctx.game,
                            &mut ctx.platform,
                            &input,
                            &mut ctx.audio,
                            dt,
                        );
                        hot_game::trino_game_render(&mut ctx.game, &mut ctx.renderer);
                    }
                    #[cfg(not(feature = "reload"))]
                    {
                        ctx.game
                            .update_with(&mut ctx.platform, &input, &mut ctx.audio, dt);
                        ctx.game.render(&mut ctx.renderer);
                    }
                }

                self.frames += 1;
                self.meter.record(
                    &trino_core::Renderer::stats(&ctx.renderer),
                    &ctx.renderer.pc_gpu_rejects(),
                );
                if let Some(max) = self.smoke_frames
                    && self.frames >= max
                {
                    println!("{}", self.meter.line(&run_label()));
                    println!("{}", trino_runner_pc::texture_line(&ctx.renderer));
                    event_loop.exit();
                    return;
                }
                ctx.window.request_redraw();
            }
            _ => {}
        }
    }
}

/// The `TRINO_FRAME:` line's name for this run: the scene file, else the
/// game.
fn run_label() -> String {
    std::env::var("TRINO_SCENE")
        .ok()
        .or_else(|| std::env::var("TRINO_GAME").ok())
        .unwrap_or_else(|| "castle64".into())
}

fn main() {
    let smoke_frames = std::env::var("TRINO_SMOKE_FRAMES")
        .ok()
        .and_then(|v| v.parse().ok());
    let profile = trino_runner_pc::profile_from_env();
    if solid_eleven() && std::env::var_os("TRINO_SCENE").is_none() {
        let mut config = trino_runner_pc::RunConfig::new("Solid Eleven", "examples/solid-eleven");
        config.target = PathBuf::from("target/solid-eleven");
        config.save_name = "solid-eleven".into();
        config.default_profile = Some(trino_platform_pc::SimProfile::Native);
        trino_runner_pc::run(config, solid_eleven::SolidElevenGame::new);
        return;
    }

    let event_loop = EventLoop::new().expect("failed to create event loop");
    let mut app = App {
        ctx: None,
        profile,
        frames: 0,
        smoke_frames,
        meter: trino_platform_pc::FrameMeter::new(profile),
    };
    event_loop.run_app(&mut app).expect("event loop error");
}
