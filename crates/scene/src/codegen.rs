//! Scene → `no_std` Rust data (`trino_core::scene::SceneNode`), so console
//! games can ship editor-made scenes with zero runtime parsing:
//!
//! ```text
//! cargo xtask scene export scenes/level1.scene.ron examples/mygame/src/level1_gen.rs
//! ```
//!
//! The output is deterministic (stable diffs) and marked as generated.

use std::fmt::Write;

use trino_core::{Color, Shading};

use crate::{Library, Scene, resolve};

fn f(v: f32) -> String {
    // `{:?}` always prints a decimal point or exponent: a valid f32 literal.
    let v = if v == 0.0 { 0.0 } else { v }; // no "-0.0" churn
    format!("{v:?}")
}

fn color(c: Color) -> String {
    format!("Color::rgba({}, {}, {}, {})", c.r, c.g, c.b, c.a)
}

fn esc(s: &str) -> String {
    s.replace('\\', "\\\\").replace('"', "\\\"")
}

/// Generate the Rust module text for `scene`. Returns (code, warnings).
pub fn to_rust(scene: &Scene, lib: &Library) -> (String, Vec<String>) {
    let resolved = resolve(scene, lib, 0.0);
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// @generated by trino-scene from scene `{}` — do not edit.\n\
         // Regenerate: cargo xtask scene export <scene.ron> <this file>\n",
        esc(&scene.name)
    );
    let _ = writeln!(
        out,
        "#[allow(unused_imports)]\nuse trino_core::{{\n    Camera3, ClipId, Collider, Color, Fog, Light, Mat34, ModelId, ModelParams, SceneNode,\n    Shading, Shape, SpriteId, Tags, Vec3,\n}};\n"
    );
    let env = &scene.environment;
    let cam = env.core_camera();
    let light = env.core_light();
    let _ = writeln!(
        out,
        "pub const CLEAR: Color = Color::rgb({}, {}, {});",
        env.clear[0], env.clear[1], env.clear[2]
    );
    let _ = writeln!(
        out,
        "pub const CAMERA: Camera3 = Camera3 {{\n    eye: Vec3::new({}, {}, {}),\n    target: Vec3::new({}, {}, {}),\n    fov_y: {},\n}};",
        f(cam.eye.x),
        f(cam.eye.y),
        f(cam.eye.z),
        f(cam.target.x),
        f(cam.target.y),
        f(cam.target.z),
        f(cam.fov_y)
    );
    let _ = writeln!(
        out,
        "pub const LIGHT: Light = Light {{\n    dir: Vec3::new({}, {}, {}),\n    ambient: {},\n    color: {},\n    ambient_color: {},\n    fog: Fog {{ color: {}, near: {}, far: {} }},\n}};\n",
        f(light.dir.x),
        f(light.dir.y),
        f(light.dir.z),
        f(light.ambient),
        color(light.color),
        color(light.ambient_color),
        color(light.fog.color),
        f(light.fog.near),
        f(light.fog.far)
    );

    let _ = writeln!(out, "pub static NODES: &[SceneNode] = &[");
    for item in resolved
        .items
        .iter()
        .filter(|i| i.sprite.is_none() || i.model.is_some())
    {
        let m = &item.matrix.m;
        let rows: Vec<String> = m
            .iter()
            .map(|r| format!("[{}, {}, {}, {}]", f(r[0]), f(r[1]), f(r[2]), f(r[3])))
            .collect();
        let model = match &item.model {
            Some((id, path)) => format!("Some(ModelId({:#010x})) /* {} */", id.0, esc(path)),
            None => "None".into(),
        };
        let p = &item.params;
        let shading = match p.shading {
            Shading::Gouraud => "Gouraud",
            Shading::Flat => "Flat",
            Shading::Unlit => "Unlit",
        };
        let anim = match p.anim {
            Some(a) => {
                // resolve() ran at t = 0 with time = 0 * speed; recover the
                // speed from the component.
                let speed = scene_speed(scene, &item.owner).unwrap_or(1.0);
                format!("Some((ClipId({:#010x}), {}))", a.clip.0, f(speed))
            }
            None => "None".into(),
        };
        let v3 = |v: trino_core::Vec3| format!("Vec3::new({}, {}, {})", f(v.x), f(v.y), f(v.z));
        let collider = match item.collider {
            Some(c) => {
                let shape = match c.shape {
                    trino_core::Shape::Box { half } => {
                        format!("Shape::Box {{ half: {} }}", v3(half))
                    }
                    trino_core::Shape::Sphere { radius } => {
                        format!("Shape::Sphere {{ radius: {} }}", f(radius))
                    }
                    trino_core::Shape::Capsule { radius, height } => format!(
                        "Shape::Capsule {{ radius: {}, height: {} }}",
                        f(radius),
                        f(height)
                    ),
                };
                format!(
                    "Some(Collider {{\n            shape: {shape},\n            offset: {},\n            trigger: {},\n        }})",
                    v3(c.offset),
                    c.trigger
                )
            }
            None => "None".into(),
        };
        let tags: Vec<String> = item
            .tags
            .iter()
            .map(|t| format!("\"{}\"", esc(t)))
            .collect();
        let _ = writeln!(
            out,
            "    SceneNode {{\n        name: \"{}\",\n        tags: Tags::List(&[{}]),\n        matrix: Mat34 {{\n            m: [{}],\n        }},\n        model: {},\n        params: ModelParams {{\n            tint: {},\n            emissive: {},\n            shading: Shading::{},\n            double_sided: {},\n            anim: None,\n            texture: {},\n        }},\n        anim: {},\n        collider: {},\n    }},",
            esc(&item.name),
            tags.join(", "),
            rows.join(", "),
            model,
            color(p.tint),
            color(p.emissive),
            shading,
            p.double_sided,
            match p.texture {
                Some(t) => format!("Some(SpriteId({:#010x}))", t.0),
                None => "None".into(),
            },
            anim,
            collider
        );
    }
    let _ = writeln!(out, "];");
    (out, resolved.warnings)
}

fn scene_speed(scene: &Scene, owner: &[usize]) -> Option<f32> {
    scene
        .get(owner)?
        .model
        .as_ref()?
        .anim
        .as_ref()
        .map(|a| a.speed)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{AnimComponent, Entity, ModelComponent};

    #[test]
    fn generates_deterministic_node_data() {
        let mut scene = Scene::new("demo");
        let mut e = Entity::new("robot")
            .at([1.0, 0.0, -2.0])
            .with_model(ModelComponent {
                anim: Some(AnimComponent {
                    clip: "walk".into(),
                    speed: 1.5,
                }),
                ..ModelComponent::new("models/robot")
            });
        e.tags.push("enemy".into());
        scene.entities.push(e);
        scene.entities.push(Entity::new("spawn"));
        let lib = Library::default();
        let (a, warnings) = to_rust(&scene, &lib);
        let (b, _) = to_rust(&scene, &lib);
        assert_eq!(a, b);
        assert!(warnings.is_empty());
        assert!(a.contains("name: \"robot\""));
        assert!(a.contains("tags: Tags::List(&[\"enemy\"])"));
        assert!(a.contains(&format!(
            "ModelId({:#010x})",
            trino_core::asset_id("models/robot")
        )));
        assert!(a.contains(&format!(
            "ClipId({:#010x}), 1.5",
            trino_core::asset_id("walk")
        )));
        assert!(a.contains("name: \"spawn\""));
        assert!(a.contains("pub const CAMERA"));
    }
}
