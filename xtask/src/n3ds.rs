//! 3DS pipeline: local devkitPro (arm-none-eabi-gcc, tex3ds, 3dsxtool) ->
//! host cargo (nightly, build-std, built-in `armv6k-nintendo-3ds` target) ->
//! `.3dsx` -> Azahar.
//!
//! Unlike the N64 there is no Docker step and no ABI hazard: devkitPro is a
//! local install, both sides of the FFI are ARM EABI-hf, and the Rust target
//! ships in rustc (Tier 3). The C shim exists because citro2d is mostly
//! static-inline C — and to keep the two console backends symmetrical.
//!
//! Test protocol: Azahar logs `svcOutputDebugString` output to its log file;
//! the harness tails it for the TRINO_TEST_* magic strings.

use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode};
use std::time::{Duration, Instant};

use trino_asset_pipeline::{Manifest, Platform, resolve_source};

use crate::project::Project;

const TARGET: &str = "armv6k-nintendo-3ds";

pub(crate) fn exe(name: &str) -> String {
    if cfg!(windows) {
        format!("{name}.exe")
    } else {
        name.to_string()
    }
}

/// devkitPro root: $DEVKITPRO when it is a real directory (on Windows the
/// installer registers the msys2-style `/opt/devkitpro`, useless outside
/// msys2), else the platform default install location.
pub(crate) fn devkitpro() -> Result<PathBuf, String> {
    let mut candidates: Vec<PathBuf> = Vec::new();
    if let Ok(env) = std::env::var("DEVKITPRO") {
        candidates.push(PathBuf::from(env));
    }
    candidates.push(PathBuf::from(r"C:\devkitPro"));
    candidates.push(PathBuf::from("/opt/devkitpro"));
    candidates
        .into_iter()
        .find(|p| p.join("libctru").is_dir())
        .ok_or_else(|| {
            "devkitPro (with libctru) not found — install it from \
             https://devkitpro.org (packages: 3ds-dev)"
                .to_string()
        })
}

fn tool(dkp: &Path, rel: &str, name: &str) -> Result<PathBuf, String> {
    let p = dkp.join(rel).join(exe(name));
    if p.exists() {
        Ok(p)
    } else {
        Err(format!("{name} not found at {}", p.display()))
    }
}

/// The shim's vertex shaders: `tri3d` maps CPU-projected triangles to the
/// screen, `tnl3d` transforms and lights static meshes on the GPU, `water`
/// displaces and shades water surfaces on the GPU (ADR 0015).
const SHADERS: [&str; 3] = ["tri3d", "tnl3d", "water"];

/// Assemble each vertex shader with picasso and embed its `.shbin` as a C
/// array (`target/3ds/<name>_shbin.h`) for the shim.
fn compile_shader(root: &Path, dkp: &Path) -> Result<(), String> {
    std::fs::create_dir_all(root.join("target/3ds")).map_err(|e| e.to_string())?;
    let picasso = tool(dkp, "tools/bin", "picasso")?;
    for name in SHADERS {
        let src = root.join(format!("crates/platform-3ds/shim/{name}.v.pica"));
        let shbin = root.join(format!("target/3ds/{name}.shbin"));
        let header = root.join(format!("target/3ds/{name}_shbin.h"));
        let status = Command::new(&picasso)
            .arg("-o")
            .arg(&shbin)
            .arg(&src)
            .status()
            .map_err(|e| format!("picasso: {e}"))?;
        if !status.success() {
            return Err(format!("picasso failed on {name}.v.pica"));
        }
        let bytes = std::fs::read(&shbin).map_err(|e| e.to_string())?;
        let mut h = format!(
            "// @generated by cargo xtask build 3ds from {name}.v.pica — do not edit.\n\
             static const unsigned char {name}_shbin[] __attribute__((aligned(4))) = {{"
        );
        for (i, b) in bytes.iter().enumerate() {
            if i % 16 == 0 {
                h.push_str("\n    ");
            }
            h.push_str(&format!("0x{b:02x},"));
        }
        h.push_str(&format!(
            "\n}};\nstatic const unsigned int {name}_shbin_size = {};\n",
            bytes.len()
        ));
        // Unchanged header keeps the shim's mtime cache valid.
        if std::fs::read_to_string(&header).ok().as_deref() != Some(h.as_str()) {
            std::fs::write(&header, h).map_err(|e| e.to_string())?;
        }
    }
    Ok(())
}

/// Compile the C shim with devkitARM's gcc against the installed libctru
/// headers (mtime-cached on the shim source and the shader header).
fn compile_shim(root: &Path, dkp: &Path) -> Result<(), String> {
    compile_shader(root, dkp)?;
    let shim_src = root.join("crates/platform-3ds/shim/trino_shim_3ds.c");
    let shader_h = root.join("target/3ds/tri3d_shbin.h");
    let tnl_h = root.join("target/3ds/tnl3d_shbin.h");
    let water_h = root.join("target/3ds/water_shbin.h");
    let shim_obj = root.join("target/3ds/shim.o");
    let newest_input = [&shim_src, &shader_h, &tnl_h, &water_h]
        .iter()
        .filter_map(|p| p.metadata().and_then(|m| m.modified()).ok())
        .max();
    if let (Some(src_time), Ok(obj_time)) =
        (newest_input, shim_obj.metadata().and_then(|m| m.modified()))
        && obj_time >= src_time
    {
        return Ok(());
    }
    println!("[3ds] compiling C shim...");
    std::fs::create_dir_all(root.join("target/3ds")).map_err(|e| e.to_string())?;
    let gcc = tool(dkp, "devkitARM/bin", "arm-none-eabi-gcc")?;
    let status = Command::new(&gcc)
        .args([
            "-c",
            "-std=gnu17",
            "-march=armv6k",
            "-mtune=mpcore",
            "-mfloat-abi=hard",
            "-mtp=soft",
            "-O2",
            "-mword-relocations",
            "-ffunction-sections",
            "-fdata-sections",
            "-D__3DS__",
        ])
        .arg(format!("-I{}", dkp.join("libctru/include").display()))
        .arg(format!("-I{}", root.join("target/3ds").display()))
        .arg(root.join("crates/platform-3ds/shim/trino_shim_3ds.c"))
        .arg("-o")
        .arg(&shim_obj)
        .status()
        .map_err(|e| format!("gcc: {e}"))?;
    if !status.success() {
        return Err("shim compilation failed".into());
    }
    Ok(())
}

/// The installed `tex3ds` (`texture inspect` decodes its output).
pub fn tex3ds_tool() -> Result<PathBuf, String> {
    tool(&devkitpro()?, "tools/bin", "tex3ds")
}

/// `tex3ds -f` for a manifest format (`trino_asset_pipeline::N3dsFormat`).
fn tex3ds_format(logical: &str, format: &str) -> Result<&'static str, String> {
    trino_asset_pipeline::N3dsFormat::parse(format)
        .map(|f| f.tex3ds())
        .ok_or_else(|| format!("{logical}: no tex3ds mapping for format {format}"))
}

/// The 3DS textures of a bake: linear memory taken against RGBA8, and how
/// many of each format (`[3ds] textures:` line).
#[derive(Default)]
struct TextureTally {
    bytes: u64,
    rgba8: u64,
    formats: std::collections::BTreeMap<String, u32>,
}

impl TextureTally {
    fn add(&mut self, c: &trino_asset_pipeline::texture::Choice, w: u32, h: u32) {
        self.bytes += c.bytes;
        self.rgba8 += trino_asset_pipeline::N3dsFormat::Rgba8.texture_bytes(w, h);
        *self.formats.entry(c.format.clone()).or_default() += 1;
    }

    fn line(&self) -> String {
        let formats: Vec<String> = self
            .formats
            .iter()
            .map(|(f, n)| format!("{f} x{n}"))
            .collect();
        format!(
            "[3ds] textures: {} B of linear memory ({} B as RGBA8): {}",
            self.bytes,
            self.rgba8,
            formats.join(", ")
        )
    }
}

/// Bake 3DS assets into target/3ds/romfs: tex3ds for sprites, `T3AU`
/// (DSP-ADPCM or PCM16, [`bake_t3au`]) for sounds and music, the project's
/// mix, plus the index.tsv the runtime reads at boot.
pub fn bake_assets(p: &Project, test_mode: bool) -> Result<(), String> {
    let root = &p.root;
    let dkp = devkitpro()?;
    let tex3ds = tool(&dkp, "tools/bin", "tex3ds")?;
    let manifest = Manifest::load(&root.join("assets/manifest.toml"))?;

    let stage = root.join("target/3ds/stage");
    let romfs = root.join("target/3ds/romfs");
    let _ = std::fs::remove_dir_all(&stage);
    let _ = std::fs::remove_dir_all(&romfs);
    std::fs::create_dir_all(&stage).map_err(|e| e.to_string())?;
    std::fs::create_dir_all(&romfs).map_err(|e| e.to_string())?;

    let mut index = String::new();
    let mut textures = TextureTally::default();

    println!("[3ds] baking assets...");
    for (name, decl) in &manifest.sprites {
        let logical = format!("sprites/{name}");
        let id = trino_core::asset_id(&logical);
        let source = resolve_source(&root.join("assets"), Platform::N3ds, &decl.file)?;
        // `auto` (the default) measures the master: the same choice as the
        // PC bake's 3DS preview.
        let (w, h, rgba) = trino_asset_pipeline::decode_png(&source)?;
        let choice = trino_asset_pipeline::texture::choose(
            Platform::N3ds,
            &logical,
            trino_asset_pipeline::texture::Source::Sprite,
            &decl.settings(Platform::N3ds),
            w,
            h,
            &rgba,
        )?;
        textures.add(&choice, w, h);
        // Manifest names follow the hardware format; tex3ds spells them
        // lowercase-compact.
        let tex3ds_format = tex3ds_format(&logical, &choice.format)?;
        let staged = stage.join(format!("{id:08x}.png"));
        std::fs::copy(&source, &staged).map_err(|e| e.to_string())?;
        let out = romfs.join(format!("{id:08x}.t3x"));
        let status = Command::new(&tex3ds)
            .arg("-f")
            .arg(tex3ds_format)
            .arg("-o")
            .arg(&out)
            .arg(&staged)
            .status()
            .map_err(|e| format!("tex3ds: {e}"))?;
        if !status.success() {
            return Err(format!("tex3ds failed for {logical}"));
        }
        index.push_str(&format!("{id:08x}\tsprite\t{id:08x}.t3x\n"));
    }
    // Sounds and music: one `T3AU` each (DSP-ADPCM unless the manifest says
    // `pcm`; issue #53). Streamed tracks stay in the RomFS and play chunk by
    // chunk; the rest load whole into linear memory at boot.
    let mut audio = AudioTally::default();
    let sections = [
        ("sounds", "sound", false, &manifest.sounds),
        ("music", "music", true, &manifest.music),
    ];
    for (prefix, kind, music, section) in sections {
        for (name, decl) in section {
            let logical = format!("{prefix}/{name}");
            let id = trino_core::asset_id(&logical);
            let source = resolve_source(&root.join("assets"), Platform::N3ds, &decl.file)?;
            let blob =
                bake_t3au(&source, decl, music, id).map_err(|e| format!("`{logical}`: {e}"))?;
            audio.add(&blob);
            std::fs::write(romfs.join(format!("{id:08x}.t3au")), &blob)
                .map_err(|e| e.to_string())?;
            index.push_str(&format!("{id:08x}\t{kind}\t{id:08x}.t3au\n"));
        }
    }
    // The project's mix (`assets/audio.toml`): bus volumes and duck rules
    // the runtime applies at boot.
    let mix = root
        .join("assets")
        .join(trino_asset_pipeline::audio::MixFile::FILE);
    if mix.exists() {
        let text = std::fs::read_to_string(&mix).map_err(|e| format!("{}: {e}", mix.display()))?;
        let blob = trino_asset_pipeline::audio::MixFile::parse(&text)
            .and_then(|m| m.bake())
            .map_err(|e| format!("{}: {e}", mix.display()))?;
        let id = trino_core::asset_id(trino_core::MixerConfig::LOGICAL);
        std::fs::write(romfs.join(format!("{id:08x}.mixer")), blob).map_err(|e| e.to_string())?;
        index.push_str(&format!("{id:08x}\tmixer\t{id:08x}.mixer\n"));
    }
    for (name, decl) in &manifest.models {
        // A model only the expanded tier names is in the image too, loaded
        // on that hardware only (issue #54).
        let Some(tier) = trino_asset_pipeline::tier::model_tier(decl, Platform::N3ds) else {
            continue;
        };
        let logical = format!("models/{name}");
        let id = trino_core::asset_id(&logical);
        let source = resolve_source(&root.join("assets"), Platform::N3ds, &decl.file)?;
        // TMDL is portable: same blob on every platform, no container tool.
        let blob = trino_asset_pipeline::bake_model(&source, &decl.options())?;
        let file = format!("{id:08x}.tmdl");
        std::fs::write(romfs.join(&file), blob).map_err(|e| e.to_string())?;
        index.push_str(&trino_asset_pipeline::tier::index_line(
            id, "model", &file, tier,
        ));
    }

    for (name, decl) in &manifest.fonts {
        let logical = format!("fonts/{name}");
        let id = trino_core::asset_id(&logical);
        let source = resolve_source(&root.join("assets"), Platform::N3ds, &decl.file)?;
        let font = trino_asset_pipeline::bake_font(&source, decl)
            .map_err(|e| format!("font `{logical}`: {e}"))?;
        let choice = trino_asset_pipeline::texture::choose(
            Platform::N3ds,
            &logical,
            trino_asset_pipeline::texture::Source::FontAtlas,
            &decl.settings(Platform::N3ds),
            font.width,
            font.height,
            &font.rgba,
        )?;
        textures.add(&choice, font.width, font.height);
        let tex3ds_format = tex3ds_format(&logical, &choice.format)?;
        // Atlas -> t3x (same handle as the font); table -> verbatim TFNT.
        let staged = stage.join(format!("{id:08x}.png"));
        let png = trino_asset_pipeline::font::encode_png(font.width, font.height, &font.rgba)?;
        std::fs::write(&staged, png).map_err(|e| e.to_string())?;
        let out = romfs.join(format!("{id:08x}.t3x"));
        let status = Command::new(&tex3ds)
            .arg("-f")
            .arg(tex3ds_format)
            .arg("-o")
            .arg(&out)
            .arg(&staged)
            .status()
            .map_err(|e| format!("tex3ds: {e}"))?;
        if !status.success() {
            return Err(format!("tex3ds failed for {logical}"));
        }
        std::fs::write(romfs.join(format!("{id:08x}.font")), &font.table)
            .map_err(|e| e.to_string())?;
        index.push_str(&format!("{id:08x}\tsprite\t{id:08x}.t3x\n"));
        index.push_str(&format!("{id:08x}\tfont\t{id:08x}.font\n"));
    }
    for (name, decl) in &manifest.blobs {
        let logical = format!("blobs/{name}");
        let id = trino_core::asset_id(&logical);
        let source = resolve_source(&root.join("assets"), Platform::N3ds, &decl.file)?;
        std::fs::copy(&source, romfs.join(format!("{id:08x}.blob"))).map_err(|e| e.to_string())?;
        index.push_str(&format!("{id:08x}\tblob\t{id:08x}.blob\n"));
    }
    for (name, decl) in &manifest.particles {
        let logical = format!("particles/{name}");
        let id = trino_core::asset_id(&logical);
        // This platform's cap (0 = the effect is off here).
        let source = trino_asset_pipeline::resolve_source(
            &root.join("assets"),
            trino_asset_pipeline::Platform::N3ds,
            &decl.file,
        )?;
        // Each hardware tier's cap: a `base` and an `expanded` copy when
        // they differ (issue #54).
        let twins = trino_asset_pipeline::tier_twins(Platform::N3ds, |t| {
            trino_asset_pipeline::particles::bake(&source, t)
        })?;
        for twin in twins {
            std::fs::write(romfs.join(twin.file(id, "blob")), &twin.bytes)
                .map_err(|e| e.to_string())?;
            index.push_str(&twin.index_line(id, "blob", "blob"));
        }
    }
    for (name, decl) in &manifest.scenes {
        let logical = format!("scenes/{name}");
        let id = trino_core::asset_id(&logical);
        // TSCN is portable; the variants resolve per hardware tier (a
        // `base` and an `expanded` copy when they differ, issue #54).
        let twins = trino_asset_pipeline::tier_twins(Platform::N3ds, |t| {
            trino_asset_pipeline::bake_scene_for(&root.join("assets"), &decl.file, t)
        })?;
        for twin in twins {
            std::fs::write(romfs.join(twin.file(id, "blob")), &twin.bytes)
                .map_err(|e| e.to_string())?;
            index.push_str(&twin.index_line(id, "blob", "blob"));
        }
    }

    std::fs::write(romfs.join("index.tsv"), index).map_err(|e| e.to_string())?;
    println!("{}", textures.line());
    println!("{}", audio.line());
    if test_mode {
        std::fs::write(romfs.join("test_mode"), "1").map_err(|e| e.to_string())?;
    }
    // `[3ds] speedup = false` (or `--speedup off`): the app leaves a New
    // 3DS at 268 MHz, the base tier (issue #54).
    if !p.n3ds_speedup {
        std::fs::write(romfs.join("no_speedup"), "1").map_err(|e| e.to_string())?;
    }
    Ok(())
}

/// A master -> the `T3AU` the shim's `trino_wav_load` reads
/// (`trino_asset_pipeline::audio::n3ds_container`): the manifest's codec,
/// rate, loop, stream and bus for the 3DS.
fn bake_t3au(
    master: &Path,
    decl: &trino_asset_pipeline::manifest::SoundDecl,
    music: bool,
    id: u32,
) -> Result<Vec<u8>, String> {
    let settings = decl.audio_settings(music, Platform::N3ds)?;
    let master = trino_asset_pipeline::bake::decode_master(master)?;
    let enc = trino_asset_pipeline::audio::encode(Platform::N3ds, &settings, &master, id)?;
    enc.blob.ok_or_else(|| "no 3DS container".into())
}

/// What the audio costs on the 3DS: RomFS bytes, and the linear memory the
/// non-streamed sounds take at boot (streams take their three chunks only
/// while they play).
#[derive(Default)]
struct AudioTally {
    count: usize,
    streamed: usize,
    romfs: usize,
    /// The same audio as PCM16 (the format before issue #53).
    pcm16: usize,
    resident: usize,
}

impl AudioTally {
    fn add(&mut self, blob: &[u8]) {
        self.count += 1;
        self.romfs += blob.len();
        if let Ok(t) = trino_asset_pipeline::audio::T3au::parse(blob) {
            self.pcm16 += t.samples * 2;
            if t.stream {
                self.streamed += 1;
            } else {
                self.resident += t.data.len();
            }
        }
    }

    fn line(&self) -> String {
        format!(
            "[3ds] audio: {} sounds ({} streamed), {} B in RomFS ({} B as PCM16), {} B resident in linear memory",
            self.count, self.streamed, self.romfs, self.pcm16, self.resident
        )
    }
}

fn cargo_build(p: &Project, dkp: &Path) -> Result<(), String> {
    println!("[3ds] building Rust ({}, build-std)...", p.nightly);
    // The target's linker is arm-none-eabi-gcc (found via PATH) and its spec
    // already carries -specs=3dsx.specs; we only add the shim + libraries.
    let path = std::env::var("PATH").unwrap_or_default();
    let sep = if cfg!(windows) { ';' } else { ':' };
    let path = format!("{}{sep}{path}", dkp.join("devkitARM/bin").display());

    let shim = p.engine.join("target/3ds/shim.o");
    let rustflags = format!(
        "-Cpanic=abort -Clink-arg={shim} -Clink-arg=-L{libs} \
         -Clink-arg=-lcitro2d -Clink-arg=-lcitro3d -Clink-arg=-lctru -Clink-arg=-lm",
        shim = shim.display(),
        libs = dkp.join("libctru/lib").display(),
    );

    let status = Command::new("cargo")
        .args([
            &format!("+{}", p.nightly),
            "build",
            "--release",
            "-Zbuild-std=core,alloc",
            "--target",
            TARGET,
            "-p",
            &p.n3ds_package,
        ])
        .current_dir(&p.root)
        .env("PATH", path)
        .env("RUSTFLAGS", rustflags)
        // apps/3ds/build.rs watches it: a shim-only edit still relinks.
        .env("TRINO_3DS_SHIM", &shim)
        .env_remove("CARGO")
        .env_remove("RUSTC")
        .status()
        .map_err(|e| format!("cargo: {e}"))?;
    if !status.success() {
        return Err("3DS Rust build failed".into());
    }
    Ok(())
}

/// smdh metadata + 3dsxtool (ELF + RomFS -> .3dsx).
fn pack_3dsx(p: &Project, dkp: &Path) -> Result<(), String> {
    println!("[3ds] packing .3dsx...");
    let smdhtool = tool(dkp, "tools/bin", "smdhtool")?;
    let tool_3dsx = tool(dkp, "tools/bin", "3dsxtool")?;
    let smdh = p.root.join(format!("target/3ds/{}.smdh", p.name));
    let icon = p
        .n3ds_icon
        .clone()
        .unwrap_or_else(|| dkp.join("libctru/default_icon.png"));
    let status = Command::new(&smdhtool)
        .args(["--create", &p.title, &p.description, &p.author])
        .arg(&icon)
        .arg(&smdh)
        .status()
        .map_err(|e| format!("smdhtool: {e}"))?;
    if !status.success() {
        return Err("smdhtool failed".into());
    }
    let status = Command::new(&tool_3dsx)
        .arg(p.n3ds_elf())
        .arg(p.app_3dsx())
        .arg(format!("--smdh={}", smdh.display()))
        .arg(format!(
            "--romfs={}",
            p.root.join("target/3ds/romfs").display()
        ))
        .status()
        .map_err(|e| format!("3dsxtool: {e}"))?;
    if !status.success() {
        return Err("3dsxtool failed".into());
    }
    println!("[3ds] app: {}", p.app_3dsx().display());
    Ok(())
}

pub fn build(p: &Project, test_mode: bool) -> ExitCode {
    let steps = || -> Result<(), String> {
        let dkp = devkitpro()?;
        compile_shim(&p.engine, &dkp)?;
        bake_assets(p, test_mode)?;
        cargo_build(p, &dkp)?;
        pack_3dsx(p, &dkp)?;
        Ok(())
    };
    match steps() {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("[3ds] {e}");
            ExitCode::FAILURE
        }
    }
}

/// Azahar executable: $TRINO_AZAHAR, `target/emulators/azahar` (from
/// `cargo xtask emulators setup azahar`), the default install location, or
/// PATH.
fn azahar_exe() -> Option<PathBuf> {
    if let Ok(env) = std::env::var("TRINO_AZAHAR") {
        let p = PathBuf::from(env);
        if p.exists() {
            return Some(p);
        }
    }
    // `cargo xtask emulators setup azahar`.
    if let Some(p) = crate::emulators::local_azahar(&crate::project::engine_root()) {
        return Some(p);
    }
    if let Ok(local) = std::env::var("LOCALAPPDATA") {
        let p = PathBuf::from(local)
            .join("Programs/Azahar")
            .join(exe("azahar"));
        if p.exists() {
            return Some(p);
        }
    }
    which(&exe("azahar"))
}

pub(crate) fn which(name: &str) -> Option<PathBuf> {
    let path = std::env::var_os("PATH")?;
    std::env::split_paths(&path)
        .map(|d| d.join(name))
        .find(|p| p.exists())
}

/// Azahar's rotating log file (svcOutputDebugString ends up here) and its
/// `qt-config.ini`. Windows keeps both under `%APPDATA%/Azahar`; Linux
/// builds use XDG dirs named `azahar-emu` (older builds: `~/.local/share/
/// Azahar`). The first candidate whose config exists wins.
fn azahar_paths() -> Option<(PathBuf, PathBuf)> {
    let candidates: Vec<(PathBuf, PathBuf)> = if cfg!(windows) {
        let base = PathBuf::from(std::env::var("APPDATA").ok()?).join("Azahar");
        vec![(
            base.join("log/azahar_log.txt"),
            base.join("config/qt-config.ini"),
        )]
    } else {
        let home = PathBuf::from(std::env::var("HOME").ok()?);
        let data = std::env::var("XDG_DATA_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|_| home.join(".local/share"));
        let config = std::env::var("XDG_CONFIG_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|_| home.join(".config"));
        vec![
            (
                data.join("azahar-emu/log/azahar_log.txt"),
                config.join("azahar-emu/qt-config.ini"),
            ),
            (
                data.join("Azahar/log/azahar_log.txt"),
                data.join("Azahar/config/qt-config.ini"),
            ),
        ]
    };
    let first = candidates.first().cloned();
    candidates
        .into_iter()
        .find(|(_, ini)| ini.exists())
        .or(first)
}

/// Minimal qt-config.ini for an Azahar that never ran: Debug-level
/// emulated output reaches the log and is flushed per line, no update
/// check or close prompt.
const AZAHAR_SEED_CONFIG: &str = "[Debugging]
instant_debug_log=true
instant_debug_log\\default=false

[Miscellaneous]
check_for_update_on_start=false
check_for_update_on_start\\default=false
log_filter=*:Info Debug.Emulated:Trace
log_filter\\default=false

[UI]
confirmClose=false
confirmClose\\default=false
";

fn azahar_log() -> Option<PathBuf> {
    azahar_paths().map(|(log, _)| log)
}

/// svcOutputDebugString logs under `Debug.Emulated` at Debug level, which
/// Azahar's default `*:Info` filter drops — the harness would time out.
/// Idempotently widen the filter in qt-config.ini.
fn ensure_azahar_log_filter() -> Result<(), String> {
    let Some((_, ini)) = azahar_paths() else {
        return Ok(()); // no HOME/APPDATA: nothing to patch
    };
    let Ok(content) = std::fs::read_to_string(&ini) else {
        // No config yet (fresh machine / CI): seed the keys the harness
        // needs; Azahar fills in every other default on first start.
        println!("[3ds] seeding {} for the test harness", ini.display());
        if let Some(dir) = ini.parent() {
            std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
        }
        return std::fs::write(&ini, AZAHAR_SEED_CONFIG).map_err(|e| e.to_string());
    };
    let mut patched = content.clone();
    if !patched.contains("Debug.Emulated") {
        patched = patched
            .replace(
                "log_filter\\default=true\r\n",
                "log_filter\\default=false\r\n",
            )
            .replace("log_filter\\default=true\n", "log_filter\\default=false\n")
            .replace(
                "log_filter=*:Info",
                "log_filter=*:Info Debug.Emulated:Trace",
            );
        if !patched.contains("Debug.Emulated") {
            return Err(format!(
                "could not widen Azahar's log_filter in {} — add `Debug.Emulated:Trace` \
                 to it manually (Emulation > Configure > Debug)",
                ini.display()
            ));
        }
    }
    // The file log only flushes on Error-level entries; without this the
    // magic strings can sit in the write buffer until Azahar exits.
    patched = patched
        .replace("instant_debug_log=false", "instant_debug_log=true")
        .replace(
            "instant_debug_log\\default=true",
            "instant_debug_log\\default=false",
        );
    if !patched.contains("instant_debug_log=true") {
        patched = patched.replacen(
            "[Debugging]\n",
            "[Debugging]\ninstant_debug_log=true\ninstant_debug_log\\default=false\n",
            1,
        );
    }
    if patched == content {
        return Ok(());
    }
    println!(
        "[3ds] configuring Azahar logging (Debug.Emulated:Trace, instant flush) for the test harness"
    );
    std::fs::write(&ini, patched).map_err(|e| e.to_string())
}

/// A boolean Azahar setting the harness forces for one session: its
/// `qt-config.ini` section and key, the name Azahar logs it under at boot,
/// and the value Azahar takes when the file says nothing.
pub struct Setting {
    pub section: &'static str,
    pub key: &'static str,
    /// The boot settings dump's name (`Renderer_Simulate3DSGPUTimings:`).
    pub log: &'static str,
    /// Suffix of the copy kept while the session runs.
    pub saved_ext: &'static str,
    pub default_on: bool,
}

/// Azahar's "Simulate 3DS GPU timings" (Emulation > Configure > Graphics),
/// under `[Renderer]`. Off by default since Azahar #2774: the emulated GPU
/// then runs at host speed, so a GPU-bound frame can look cheap. (Issue #43
/// calls it `simulate_gpu_timing`; 2126.2 reads this name and ignores that
/// one.)
pub const GPU_TIMING: Setting = Setting {
    section: "[Renderer]",
    key: "simulate_3ds_gpu_timings",
    log: "Renderer_Simulate3DSGPUTimings:",
    saved_ext: ".trino-gpu-timing",
    default_on: false,
};

/// Azahar's "New 3DS mode" (Emulation > Configure > System), under
/// `[System]`: the emulated console answers `APT_CheckNew3DS` with it and
/// runs the 804 MHz clock when the app turns the speedup on. On by default
/// in 2126.2; `test 3ds --new3ds on|off` forces it (issue #54).
pub const NEW_3DS: Setting = Setting {
    section: "[System]",
    key: "is_new_3ds",
    log: "System_IsNew3ds:",
    saved_ext: ".trino-new-3ds",
    default_on: true,
};

/// `--accurate-timing`, or `TRINO_AZAHAR_GPU_TIMING=1` (or true/on/yes).
pub fn accurate_timing(flag: bool) -> bool {
    flag || std::env::var("TRINO_AZAHAR_GPU_TIMING").is_ok_and(|v| env_on(&v))
}

fn env_on(v: &str) -> bool {
    matches!(
        v.trim().to_ascii_lowercase().as_str(),
        "1" | "true" | "on" | "yes"
    )
}

/// `--accurate-timing` only means something where Azahar runs.
pub fn check_accurate_timing(
    cmd: Option<&str>,
    platform: Option<&str>,
    real_hardware: bool,
) -> Result<(), String> {
    if real_hardware {
        return Err(
            "xtask: --accurate-timing configures Azahar; a real 3DS already has real GPU timing"
                .into(),
        );
    }
    match (cmd, platform) {
        (Some("run" | "test" | "watch"), Some("3ds" | "n3ds")) | (Some("test"), Some("all")) => {
            Ok(())
        }
        _ => Err(
            "xtask: --accurate-timing goes with `run|test|watch 3ds` (Azahar's \
                  \"Simulate 3DS GPU timings\")"
                .into(),
        ),
    }
}

/// The two lines of a setting in its section, verbatim without their line
/// ending (None: absent). Qt writes `key\default=true` when the value is
/// the default, and Azahar then ignores the value, so forcing the setting
/// takes both lines.
#[derive(Clone, Debug, Default, PartialEq)]
struct SettingLines {
    value: Option<String>,
    default: Option<String>,
}

impl SettingLines {
    fn forced(s: &Setting, on: bool) -> Self {
        Self {
            value: Some(format!("{}={on}", s.key)),
            default: Some(format!("{}\\default=false", s.key)),
        }
    }

    /// What Azahar runs with.
    fn enabled(&self, s: &Setting) -> bool {
        let at_default = self.default.as_deref() == Some(&format!("{}\\default=true", s.key));
        match self.value.as_deref() {
            Some(v) if !at_default => v == format!("{}=true", s.key),
            _ => s.default_on,
        }
    }

    /// Saved copy: one line each, empty for an absent line.
    fn to_text(&self) -> String {
        format!(
            "{}\n{}\n",
            self.value.as_deref().unwrap_or(""),
            self.default.as_deref().unwrap_or("")
        )
    }

    fn from_text(text: &str) -> Self {
        let mut it = text
            .lines()
            .map(|l| Some(l.to_string()).filter(|l| !l.is_empty()));
        Self {
            value: it.next().flatten(),
            default: it.next().flatten(),
        }
    }
}

/// `section` as a line range: the header's index and the end (exclusive).
fn section_range(lines: &[String], section: &str) -> Option<(usize, usize)> {
    let start = lines.iter().position(|l| l.trim() == section)?;
    let end = lines[start + 1..]
        .iter()
        .position(|l| l.trim_start().starts_with('['))
        .map_or(lines.len(), |i| start + 1 + i);
    Some((start, end))
}

fn setting_lines(ini: &str, s: &Setting) -> SettingLines {
    let lines: Vec<String> = ini.lines().map(str::to_string).collect();
    let Some((start, end)) = section_range(&lines, s.section) else {
        return SettingLines::default();
    };
    let find = |prefix: &str| {
        lines[start + 1..end]
            .iter()
            .find(|l| l.starts_with(prefix))
            .cloned()
    };
    SettingLines {
        value: find(&format!("{}=", s.key)),
        default: find(&format!("{}\\default=", s.key)),
    }
}

/// `ini` with the setting's lines set to `want`, every other byte kept
/// (line endings included). A missing section is appended, and one left
/// empty by removing the lines goes away again, so a set followed by a set
/// to the old lines gives the original file back.
fn with_setting(ini: &str, s: &Setting, want: &SettingLines) -> String {
    let eol = if ini.contains("\r\n") { "\r\n" } else { "\n" };
    let mut lines: Vec<String> = ini.lines().map(str::to_string).collect();
    let trailing = ini.is_empty() || ini.ends_with('\n');
    if section_range(&lines, s.section).is_none() {
        if want.value.is_none() && want.default.is_none() {
            return ini.to_string();
        }
        if lines.last().is_some_and(|l| !l.trim().is_empty()) {
            lines.push(String::new());
        }
        lines.push(s.section.into());
    }
    // The default line first: both insert under the header, value on top.
    for (prefix, line) in [
        (format!("{}\\default=", s.key), &want.default),
        (format!("{}=", s.key), &want.value),
    ] {
        let (start, end) = section_range(&lines, s.section).expect("the section exists");
        let at = (start + 1..end).find(|&i| lines[i].starts_with(&prefix));
        match (at, line) {
            (Some(i), Some(l)) => lines[i] = l.clone(),
            (None, Some(l)) => lines.insert(start + 1, l.clone()),
            (Some(i), None) => {
                lines.remove(i);
            }
            (None, None) => {}
        }
    }
    let (start, end) = section_range(&lines, s.section).expect("the section exists");
    if lines[start + 1..end].iter().all(|l| l.trim().is_empty()) {
        lines.drain(start..end);
        if start == lines.len() && start > 0 && lines[start - 1].trim().is_empty() {
            lines.pop();
        }
    }
    let mut out = lines.join(eol);
    if trailing && !out.is_empty() {
        out.push_str(eol);
    }
    out
}

/// Where a session keeps the user's lines until it puts them back.
fn setting_saved(ini: &Path, s: &Setting) -> PathBuf {
    let mut p = ini.as_os_str().to_owned();
    p.push(s.saved_ext);
    PathBuf::from(p)
}

fn restore_setting(ini: &Path, s: &Setting, saved: &SettingLines) -> Result<(), String> {
    let content = std::fs::read_to_string(ini).unwrap_or_default();
    let restored = with_setting(&content, s, saved);
    if restored != content {
        std::fs::write(ini, restored).map_err(|e| format!("{}: {e}", ini.display()))?;
    }
    let _ = std::fs::remove_file(setting_saved(ini, s));
    Ok(())
}

/// One Azahar session with a setting forced: dropping this puts the user's
/// own lines back. Azahar writes the file while it runs, so that happens
/// after it exits.
struct SettingSession {
    ini: PathBuf,
    setting: &'static Setting,
    saved: SettingLines,
}

impl Drop for SettingSession {
    fn drop(&mut self) {
        let key = self.setting.key;
        match restore_setting(&self.ini, self.setting, &self.saved) {
            Ok(()) => println!("[3ds] restored your {key} setting"),
            Err(e) => eprintln!("[3ds] could not restore {key}: {e}"),
        }
    }
}

/// Before every Azahar session: put back what an interrupted session
/// (Ctrl+C, a crash) left of `s`, then, with `want`, force it on or off
/// until the returned guard drops. Without `want` the user's setting
/// stands, whatever it is.
fn setting_session(
    s: &'static Setting,
    want: Option<bool>,
) -> Result<Option<SettingSession>, String> {
    match azahar_paths() {
        Some((_, ini)) => setting_session_at(ini, s, want),
        None => Ok(None),
    }
}

fn setting_session_at(
    ini: PathBuf,
    s: &'static Setting,
    want: Option<bool>,
) -> Result<Option<SettingSession>, String> {
    let saved_path = setting_saved(&ini, s);
    if let Ok(text) = std::fs::read_to_string(&saved_path) {
        println!("[3ds] restoring {} left by an interrupted session", s.key);
        restore_setting(&ini, s, &SettingLines::from_text(&text))?;
    }
    let Some(on) = want else {
        return Ok(None);
    };
    let content = std::fs::read_to_string(&ini).unwrap_or_default();
    let saved = setting_lines(&content, s);
    let forced = SettingLines::forced(s, on);
    if saved == forced {
        println!("[3ds] {}={on} already in {}", s.key, ini.display());
        return Ok(None);
    }
    if let Some(dir) = ini.parent() {
        std::fs::create_dir_all(dir).map_err(|e| e.to_string())?;
    }
    // The copy goes first: the ini is never changed without it.
    std::fs::write(&saved_path, saved.to_text())
        .map_err(|e| format!("{}: {e}", saved_path.display()))?;
    std::fs::write(&ini, with_setting(&content, s, &forced))
        .map_err(|e| format!("{}: {e}", ini.display()))?;
    println!(
        "[3ds] {}={on} for this session (was {})",
        s.key,
        if saved.enabled(s) { "on" } else { "off" }
    );
    Ok(Some(SettingSession {
        ini,
        setting: s,
        saved,
    }))
}

/// The setting in the configuration Azahar logged at boot, if it has.
fn setting_logged(log: &str, s: &Setting) -> Option<bool> {
    log.lines()
        .find_map(|l| l.split_once(s.log))
        .map(|(_, v)| v.trim() == "true")
}

/// `--accurate-timing` for one session: GPU timing on, the user's setting
/// back afterwards (see [`setting_session`]).
fn gpu_timing_session(accurate: bool) -> Result<Option<SettingSession>, String> {
    setting_session(&GPU_TIMING, accurate.then_some(true))
}

pub fn run(p: &Project, accurate: bool, hw: &crate::hwtier::Options) -> ExitCode {
    let code = build(p, false);
    if code != ExitCode::SUCCESS {
        return code;
    }
    let Some(azahar) = azahar_exe() else {
        eprintln!("[3ds] Azahar not found (set TRINO_AZAHAR to the executable)");
        return ExitCode::FAILURE;
    };
    let session = match gpu_timing_session(accurate) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[3ds] {e}");
            return ExitCode::FAILURE;
        }
    };
    // `--new3ds on|off`: the console Azahar emulates, for this session.
    let console = match setting_session(&NEW_3DS, hw.new3ds_run()) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[3ds] {e}");
            return ExitCode::FAILURE;
        }
    };
    println!("[3ds] launching Azahar...");
    let mut child = match Command::new(&azahar).arg(p.app_3dsx()).spawn() {
        Ok(c) => c,
        Err(e) => {
            eprintln!("[3ds] failed to launch Azahar: {e}");
            return ExitCode::FAILURE;
        }
    };
    if session.is_none() && console.is_none() {
        return ExitCode::SUCCESS;
    }
    // The override lasts as long as the emulator: wait for it, then report
    // what it booted with and put the user's setting back.
    println!("[3ds] waiting for Azahar to close (then your setting comes back)");
    let _ = child.wait();
    let log = azahar_log().and_then(|l| std::fs::read_to_string(l).ok());
    for (guard, s) in [
        (session.is_some(), &GPU_TIMING),
        (console.is_some(), &NEW_3DS),
    ] {
        if let Some(on) = log
            .as_deref()
            .filter(|_| guard)
            .and_then(|l| setting_logged(l, s))
        {
            println!("[3ds] Azahar booted with {} {on}", s.log);
        }
    }
    ExitCode::SUCCESS
}

/// Boot the self-test app in Azahar once per console mode `new3ds` asks
/// for (`--new3ds on|off|both`; a New 3DS by default, Azahar's own
/// default): one app detects its hardware at boot (issue #54).
/// `build`: false boots an existing self-test app (`cargo xtask build 3ds
/// --selftest`, e.g. a CI artifact) — Azahar's AppImage needs a newer glibc
/// than the devkitARM image has, so CI builds and boots in separate jobs.
pub fn test(
    p: &Project,
    build_first: bool,
    bless: bool,
    accurate: bool,
    new3ds: crate::hwtier::Mode,
) -> ExitCode {
    if build_first {
        let code = build(p, true);
        if code != ExitCode::SUCCESS {
            return code;
        }
    }
    // An app built elsewhere carries its own speedup setting.
    let speedup = build_first.then_some(p.n3ds_speedup);
    for &on in new3ds.runs() {
        let code = boot_test(p, bless, accurate, on, speedup);
        if code != ExitCode::SUCCESS {
            return code;
        }
    }
    ExitCode::SUCCESS
}

/// Boot the test app in Azahar (as a New or an old 3DS) and tail its log
/// file for the magic strings and the `TRINO_HW` line (the GUI build has no
/// console stdout on Windows). Kills the emulator on verdict or timeout.
fn boot_test(
    p: &Project,
    bless: bool,
    accurate: bool,
    new3ds: bool,
    speedup: Option<bool>,
) -> ExitCode {
    let root = &p.root;
    if !p.app_3dsx().exists() {
        eprintln!(
            "[3ds] {} missing (cargo xtask build 3ds --selftest)",
            p.app_3dsx().display()
        );
        return ExitCode::FAILURE;
    }
    let Some(azahar) = azahar_exe() else {
        eprintln!("[3ds] Azahar not found (set TRINO_AZAHAR to the executable)");
        return ExitCode::FAILURE;
    };
    let Some(log) = azahar_log() else {
        eprintln!("[3ds] cannot locate the Azahar log directory");
        return ExitCode::FAILURE;
    };
    if let Err(e) = ensure_azahar_log_filter() {
        eprintln!("[3ds] {e}");
        return ExitCode::FAILURE;
    }
    // After the seed above, so a fresh config gets both.
    let session = match gpu_timing_session(accurate) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[3ds] {e}");
            return ExitCode::FAILURE;
        }
    };
    let console = match setting_session(&NEW_3DS, Some(new3ds)) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[3ds] {e}");
            return ExitCode::FAILURE;
        }
    };
    let kind = if new3ds { "a New 3DS" } else { "an old 3DS" };
    // Azahar truncates the log per session; remove any stale one so we never
    // match output from a previous run.
    let _ = std::fs::remove_file(&log);

    let timeout = crate::emulators::timeout_secs();
    let idle = crate::emulators::idle_secs();
    println!(
        "[3ds] booting test app in Azahar as {kind} ({timeout}s timeout, {idle}s idle limit)..."
    );
    let mut child = match Command::new(&azahar).arg(p.app_3dsx()).spawn() {
        Ok(c) => c,
        Err(e) => {
            eprintln!("[3ds] failed to launch Azahar: {e}");
            return ExitCode::FAILURE;
        }
    };

    let mut watchdog = crate::emulators::Watchdog::new();
    let mut seen = 0usize;
    let mut fb = crate::fbgolden::FbCapture::default();
    let mut frames: Vec<crate::fbgolden::FbCapture> = Vec::new();
    let mut gpu_timing = None;
    let mut is_new = None;
    let mut hw_line = None;
    let mut tier_step = None;
    let mut quality_step = None;
    let mut worker_step = None;
    let verdict = loop {
        if let Some(why) = watchdog.expired(Instant::now()) {
            break Err(why);
        }
        if let Ok(Some(status)) = child.try_wait() {
            break Err(format!(
                "Azahar exited before reporting a verdict ({status})"
            ));
        }
        std::thread::sleep(Duration::from_millis(500));
        let Ok(content) = std::fs::read_to_string(&log) else {
            continue;
        };
        // Only whole lines: the emulator may be mid-write.
        let end = content.rfind('\n').map_or(0, |i| i + 1);
        let fresh = &content[seen.min(end)..end];
        for line in fresh.lines() {
            watchdog.saw(line, Instant::now());
            // Framebuffer dump rows are collected, not echoed; each
            // TRINO_FB_END closes one image (they arrive in order).
            if fb.feed(line) {
                if fb.done() {
                    frames.push(std::mem::take(&mut fb));
                }
                continue;
            }
            if line.contains("TRINO_") {
                println!("[azahar] {line}");
            }
            if gpu_timing.is_none() && line.contains(GPU_TIMING.log) {
                println!("[azahar] {}", line.trim());
                gpu_timing = setting_logged(line, &GPU_TIMING);
            }
            if is_new.is_none() && line.contains(NEW_3DS.log) {
                println!("[azahar] {}", line.trim());
                is_new = setting_logged(line, &NEW_3DS);
            }
            if hw_line.is_none() && line.contains("TRINO_HW 3ds") {
                hw_line = Some(line.to_string());
            }
            if line.contains("TRINO_STEP:hw tier ") {
                tier_step = Some(line.to_string());
            }
            if line.contains("TRINO_STEP:quality ") {
                quality_step = Some(line.to_string());
            }
            if line.contains("TRINO_STEP:worker ") {
                worker_step = Some(line.to_string());
            }
        }
        if fresh.contains("TRINO_TEST_PASS") {
            break Ok(());
        }
        if let Some(idx) = fresh.find("TRINO_TEST_FAIL") {
            let tail: String = fresh[idx..].lines().next().unwrap_or("").to_string();
            break Err(tail);
        }
        seen = end;
    };
    let _ = child.kill();
    let _ = child.wait();
    drop(console);
    drop(session);
    // The console Azahar emulated, and what the app saw of it (issue #54).
    let verdict = verdict.and_then(|()| {
        if is_new == Some(!new3ds) {
            return Err(format!(
                "--new3ds: Azahar booted with {} {}",
                NEW_3DS.log, !new3ds
            ));
        }
        let hw = crate::hwtier::check_3ds(hw_line.as_deref(), new3ds, speedup)?;
        println!("[3ds] hardware tier: {hw}");
        // The engine self-test loaded that tier's data (castle64's step).
        if p.is_engine {
            let data = crate::hwtier::check_data(hw_line.as_deref(), tier_step.as_deref())?;
            println!("[3ds] tier data: {data}");
            let worker = crate::hwtier::check_worker(worker_step.as_deref(), new3ds)?;
            println!("[3ds] worker core: {worker}");
            // A console's quality preset is fixed: Medium on the New 3DS,
            // Low on the old one (issue #55).
            let want = if new3ds { "medium" } else { "low" };
            let q = crate::hwtier::check_quality(quality_step.as_deref(), want)?;
            println!("[3ds] quality: {q}");
        }
        Ok(())
    });
    // An Azahar that ignored the override would time the frames without it.
    let verdict = verdict.and_then(|()| match gpu_timing {
        Some(false) if accurate => Err(format!(
            "--accurate-timing: Azahar booted with {} false",
            GPU_TIMING.log
        )),
        None if accurate => {
            println!("[3ds] note: Azahar's log does not show {}", GPU_TIMING.log);
            Ok(())
        }
        _ => Ok(()),
    });

    // Emulator frame of the castle64 hub, within a tolerance: Azahar's GPU
    // output depends on the host's OpenGL (desktop GPU vs CI's llvmpipe).
    let verdict = verdict.and_then(|()| {
        if !p.is_engine {
            let mean = p.test.n3ds_golden_mean.unwrap_or(3.0);
            return crate::n64::project_gates(
                p,
                "3ds",
                &p.test.n3ds_goldens,
                &frames,
                bless,
                Some((mean, 0.02)),
            );
        }
        let img = frames
            .first()
            .ok_or("golden frame: not dumped")?
            .image()
            .map_err(|e| format!("golden frame: {e}"))?;
        let msg = crate::fbgolden::check_close(root, "3ds", "castle64_hub", img, bless, 3.0, 0.02)?;
        println!("[3ds] golden frame: {msg}");
        // The same frame's touch screen (castle64's bottom-screen panel).
        let img = frames
            .get(1)
            .ok_or("bottom golden frame: not dumped")?
            .image()
            .map_err(|e| format!("bottom golden frame: {e}"))?;
        let msg = crate::fbgolden::check_close(
            root,
            "3ds",
            "castle64_hub_bottom",
            img,
            bless,
            3.0,
            0.02,
        )?;
        println!("[3ds] golden frame (bottom): {msg}");
        // The showcase's touch panel (metrics + look toggles), after its
        // `showcase panel` probes.
        let img = frames
            .get(2)
            .ok_or("showcase bottom golden frame: not dumped")?
            .image()
            .map_err(|e| format!("showcase bottom golden frame: {e}"))?;
        let msg =
            crate::fbgolden::check_close(root, "3ds", "showcase_bottom", img, bless, 3.0, 0.02)?;
        println!("[3ds] golden frame (showcase bottom): {msg}");
        // The showcase's river (water, ADR 0015) on the top screen.
        let img = frames
            .get(3)
            .ok_or("showcase river golden frame: not dumped")?
            .image()
            .map_err(|e| format!("showcase river golden frame: {e}"))?;
        let msg =
            crate::fbgolden::check_close(root, "3ds", "showcase_river", img, bless, 3.0, 0.02)?;
        println!("[3ds] golden frame (showcase river): {msg}");
        // One card per texture format (#52): ETC1/ETC1A4/RGBA4/... sampled
        // by the PICA200 (`castle64::selftest::draw_texture_formats`).
        let img = frames
            .get(4)
            .ok_or("texture formats golden frame: not dumped")?
            .image()
            .map_err(|e| format!("texture formats golden frame: {e}"))?;
        let msg =
            crate::fbgolden::check_close(root, "3ds", "texture_formats", img, bless, 3.0, 0.02)?;
        println!("[3ds] golden frame (texture formats): {msg}");
        Ok(())
    });

    match verdict {
        Ok(()) => {
            println!("[3ds] TEST PASS (as {kind})");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("[3ds] TEST FAIL: {e}");
            ExitCode::FAILURE
        }
    }
}

/// Console live-reload loop: watch game source + assets, rebuild the .3dsx
/// on change and relaunch Azahar (kill + relaunch, like the N64 loop).
pub fn watch(p: &Project, accurate: bool, hw: &crate::hwtier::Options) -> ExitCode {
    use std::sync::mpsc;

    use notify_debouncer_full::notify::RecursiveMode;
    use notify_debouncer_full::{DebounceEventResult, new_debouncer};

    let Some(azahar) = azahar_exe() else {
        eprintln!("[3ds] Azahar not found (set TRINO_AZAHAR to the executable)");
        return ExitCode::FAILURE;
    };
    if build(p, false) != ExitCode::SUCCESS {
        return ExitCode::FAILURE;
    }
    // Relaunches kill Azahar, which then saves nothing: the override holds
    // for the whole loop (Ctrl+C leaves it to the next 3DS command to undo).
    let _session = match gpu_timing_session(accurate) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[3ds] {e}");
            return ExitCode::FAILURE;
        }
    };
    let _console = match setting_session(&NEW_3DS, hw.new3ds_run()) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("[3ds] {e}");
            return ExitCode::FAILURE;
        }
    };

    fn launch(azahar: &Path, app: &Path) -> std::io::Result<std::process::Child> {
        Command::new(azahar).arg(app).spawn()
    }
    let app = p.app_3dsx();
    let mut child = match launch(&azahar, &app) {
        Ok(c) => c,
        Err(e) => {
            eprintln!("[3ds] failed to launch Azahar: {e}");
            return ExitCode::FAILURE;
        }
    };

    let (tx, rx) = mpsc::channel();
    let mut debouncer = match new_debouncer(
        Duration::from_millis(300),
        None,
        move |result: DebounceEventResult| {
            if let Ok(events) = result
                && crate::real_change(&events)
            {
                let _ = tx.send(());
            }
        },
    ) {
        Ok(d) => d,
        Err(e) => {
            eprintln!("[3ds] failed to start watcher: {e}");
            let _ = child.kill();
            return ExitCode::FAILURE;
        }
    };
    for dir in &p.watch {
        if let Err(e) = debouncer.watch(p.root.join(dir), RecursiveMode::Recursive) {
            eprintln!("[3ds] failed to watch {dir}/: {e}");
            let _ = child.kill();
            return ExitCode::FAILURE;
        }
    }

    println!("[3ds] watching {} — Ctrl+C to stop", p.watch.join(", "));
    loop {
        if rx.recv().is_err() {
            let _ = child.kill();
            return ExitCode::SUCCESS;
        }
        while rx.try_recv().is_ok() {}
        println!("[3ds] change detected, rebuilding...");
        if build(p, false) == ExitCode::SUCCESS {
            let _ = child.kill();
            let _ = child.wait();
            match launch(&azahar, &app) {
                Ok(c) => child = c,
                Err(e) => {
                    eprintln!("[3ds] failed to relaunch Azahar: {e}");
                    return ExitCode::FAILURE;
                }
            }
        } else {
            eprintln!("[3ds] build failed — keeping the previous app running (fix and save again)");
        }
    }
}

