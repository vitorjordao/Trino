//! # trino-fuzz
//!
//! One function per parser the engine runs on data from outside the build
//! (issue #68): baked assets a disk, a mod or a bad bake can damage, the
//! saves, the player's settings files and the network. The same bodies run
//! three ways:
//!
//! - `fuzz/` (cargo-fuzz, libFuzzer, nightly): `cargo xtask fuzz run <t>`;
//! - this crate's tests (stable, every PR): each target over its committed
//!   seeds (`fuzz/seeds/<t>/`), every crash reproducer
//!   (`fuzz/regressions/<t>/`) and a deterministic mutation run;
//! - `cargo xtask fuzz repro <file>`.
//!
//! The invariants: no panic, no out-of-bounds read (ASan in the fuzz build),
//! a written blob parses back to the same bytes where a writer exists, and
//! memory bounded by [`core_targets::MAX_DECODE`] per announced size.

pub mod core_targets;
#[cfg(feature = "host")]
pub mod gpu_targets;
#[cfg(feature = "host")]
pub mod host_targets;
pub mod mutate;
pub mod seedgen;

use std::path::{Path, PathBuf};

/// A fuzz target: a name (the cargo-fuzz binary and the corpus folder),
/// the formats it covers (four-letter magics, or a file kind), the body,
/// and the largest input worth generating.
#[derive(Clone, Copy)]
pub struct Target {
    pub name: &'static str,
    pub formats: &'static [&'static str],
    pub run: fn(&[u8]),
    pub max_len: usize,
    /// Where the seed corpus comes from (for `cargo xtask fuzz corpus`).
    pub seeds: Seeds,
}

/// How `cargo xtask fuzz corpus` finds a target's seeds.
#[derive(Clone, Copy, Debug)]
pub enum Seeds {
    /// Baked blobs whose first four bytes are one of these magics.
    Magic(&'static [&'static [u8; 4]]),
    /// Files with one of these extensions (or names) under the repo's
    /// authored content and the examples.
    Files(&'static [&'static str]),
    /// Only the committed seeds (generated by the target's own writer).
    Committed,
}

